-- ── 1. 컬럼 추가 ─────────────────────────────────────────────────────
ALTER TABLE TSKGIAF01 ADD (
    -- 🔴 코드값. 01 입찰제안서(ppt·pptx) / 02 입찰공고문 RFP(pdf·hwp·hwpx)
    --    자바는 DocType enum(BID_PROPOSAL·RFP)을 쓰고 변환은 TypeHandler 가 한다
    --    (분류상태구분 ↔ ClassificationStatus 와 같은 방식).
    문서종류구분        VARCHAR2(2 CHAR),              -- 구분코드2 · 속성명 문서종류구분코드
    -- 🔴 코드값. 01 PENDING / 02 SUCCESS / 03 FAILED
    --    ⚠️ 분류상태구분(기관분류 확정 여부)과 **다른 축**이다. 파싱은 성공했는데
    --       기관을 못 찾아 미분류인 행이 정상적으로 존재한다.
    파싱상태구분        VARCHAR2(2 CHAR),              -- 구분코드2 · 속성명 파싱상태구분코드
    -- 실패 사유를 사람이 읽는 문장으로 남긴다. 화면의 실패 배지 옆에 그대로 나온다.
    파싱메시지내용      VARCHAR2(1000 CHAR),           -- 내용1000 · 속성명 동일
    -- 파싱 산출물(제안서 JSON · RFP 요약 MD)의 전체 경로.
    -- ⚠️ 원본 경로인 `저장경로내용` 과 다르다. 원본은 userdata 폴더에 그대로 둔다.
    파싱산출물경로내용  VARCHAR2(600 CHAR),            -- 내용600 · 속성명 동일
    -- 🔴 시각이 문자열이다(사내 표준). YYYYMMDDHH24MISS 14자.
    파싱일시            VARCHAR2(14 CHAR),             -- 일시14 · 속성명 동일
    -- 제안서는 슬라이드 수, RFP 는 페이지 수. 실무 문서가 수백 장이라 5자리면 충분하다.
    문서페이지수        DECIMAL(5),                    -- 수5 · 속성명 동일
    -- 제안서는 연도(YYYY + '0101' 이 아니라 **연도 4자리만** 채운다), RFP 는 공고일(YYYYMMDD).
    -- ⚠️ 기존 `문서년 VARCHAR2(4 CHAR)` 은 **공고일 8자리를 못 담아** 새 컬럼을 만든 것이다.
    --    문서년은 지우지 않고 남긴다(옛 행이 쓰고 있다). 새 코드는 이 컬럼만 쓴다.
    문서일자            VARCHAR2(8 CHAR)               -- 년월일8 · 속성명 동일
);

