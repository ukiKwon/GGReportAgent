package com.kbstar.kgi.ggreport.web.db;

import org.junit.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/**
 * 048 PREP_NOBID_ACK DDL 쌍 — 칸 이름·순서 같음, 자연 PK 같음(일련번호 칸 없음), 11g 문법, utf8mb4. 파일만 읽는다(PlanCollectDdlPairTest 방식).
 * 주의: 번호가 바뀌면 FILE 과 테스트 application.properties 의 schema-locations 를 같이 바꾼다.
 */
public class NobidAckDdlPairTest {

    private static final Path DB = Paths.get("src/main/resources/db");
    private static final String FILE = "048_prep_nobid_ack.sql";
    private static final String TABLE = "PREP_NOBID_ACK";
    private static final String PK_COLS = "(EMP_NO, INSTITUTION_ID, ROUND_SEQ, NOTICE_HANDLED_AT)";

    private static String read(String d) throws IOException {
        Path f = DB.resolve(d).resolve(FILE);
        assertTrue(f + " 가 없다 — 작업 디렉터리가 kgi-ggreport-web/ 인지 확인", Files.exists(f));
        return new String(Files.readAllBytes(f), StandardCharsets.UTF_8).replaceAll("--[^\\r\\n]*", "");   // 주석 제거
    }

    private static List<String> columns(String d) throws IOException {
        List<String> out = new ArrayList<>();
        Set<String> skip = new HashSet<>(Arrays.asList("PRIMARY", "KEY", "CONSTRAINT", "UNIQUE", "INDEX", "FOREIGN", "CHECK"));
        Pattern word = Pattern.compile("^([A-Z][A-Z0-9_]*)\\b.*");
        boolean in = false;
        for (String raw : Files.readAllLines(DB.resolve(d).resolve(FILE), StandardCharsets.UTF_8)) {
            String line = raw.trim();
            if (line.startsWith("CREATE TABLE " + TABLE + " (")) { in = true; continue; }
            if (!in) continue;
            if (line.startsWith(")")) break;
            Matcher m = word.matcher(line);
            if (m.matches() && !skip.contains(m.group(1))) out.add(m.group(1));
        }
        return out;
    }

    @Test
    public void 칸_이름과_순서가_같고_일련번호_칸이_없다() throws IOException {
        List<String> o = columns("oracle");
        assertEquals(12, o.size());
        assertEquals(o, columns("mysql"));
        assertFalse(o.contains("ACK_ID"));
    }

    @Test
    public void 자연_PK가_양쪽에_같다() throws IOException {
        assertTrue(read("oracle").contains("CONSTRAINT PK_PREP_NOBID_ACK PRIMARY KEY " + PK_COLS));
        assertTrue(read("mysql").contains("PRIMARY KEY " + PK_COLS));
    }

    @Test
    public void Oracle은_11g_문법이고_MySQL은_utf8mb4를_먼저_지정한다() throws IOException {
        String o = read("oracle");
        assertFalse(o.contains("GENERATED BY"));
        assertFalse(o.contains("FETCH FIRST"));
        String m = read("mysql");
        assertFalse(m.contains("AUTO_INCREMENT"));
        assertTrue(m.contains("SET NAMES utf8mb4;"));
    }
}
