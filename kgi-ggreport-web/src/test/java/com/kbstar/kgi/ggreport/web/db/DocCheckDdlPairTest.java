package com.kbstar.kgi.ggreport.web.db;

import org.junit.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/**
 * 057 DOC_CHECK · DOC_CHECK_HIT · DOC_CHECK_LOG DDL 쌍(NEXT 106) — 칸 이름·순서 같음, 자연 PK 같음, 11g 문법, utf8mb4, 파일 이름 칸 없음(대외비).
 * 파일만 읽는다(NobidAckDdlPairTest 방식). 주의: 번호가 바뀌면 FILE 과 테스트 application.properties 의 schema-locations 를 같이 바꾼다.
 */
public class DocCheckDdlPairTest {

    private static final Path DB = Paths.get("src/main/resources/db");
    private static final String FILE = "057_doc_check.sql";

    private static String read(String d) throws IOException {
        Path f = DB.resolve(d).resolve(FILE);
        assertTrue(f + " 가 없다 — 작업 디렉터리가 kgi-ggreport-web/ 인지 확인", Files.exists(f));
        return new String(Files.readAllBytes(f), StandardCharsets.UTF_8).replaceAll("--[^\\r\\n]*", "");   // 주석 제거
    }

    private static List<String> columns(String d, String table) throws IOException {
        List<String> out = new ArrayList<>();
        Set<String> skip = new HashSet<>(Arrays.asList("PRIMARY", "KEY", "CONSTRAINT", "UNIQUE", "INDEX", "FOREIGN", "CHECK"));
        Pattern word = Pattern.compile("^([A-Z][A-Z0-9_]*)\\b.*");
        boolean in = false;
        for (String raw : Files.readAllLines(DB.resolve(d).resolve(FILE), StandardCharsets.UTF_8)) {
            String line = raw.trim();
            if (line.startsWith("CREATE TABLE " + table + " (")) { in = true; continue; }
            if (!in) continue;
            if (line.startsWith(")")) break;
            Matcher m = word.matcher(line);
            if (m.matches() && !skip.contains(m.group(1))) out.add(m.group(1));
        }
        return out;
    }

    @Test
    public void 세_표의_칸_이름과_순서가_양쪽에_같다() throws IOException {
        assertEquals(14, columns("oracle", "DOC_CHECK").size());
        assertEquals(columns("oracle", "DOC_CHECK"), columns("mysql", "DOC_CHECK"));
        assertEquals(6, columns("oracle", "DOC_CHECK_HIT").size());
        assertEquals(columns("oracle", "DOC_CHECK_HIT"), columns("mysql", "DOC_CHECK_HIT"));
        assertEquals(17, columns("oracle", "DOC_CHECK_LOG").size());
        assertTrue(columns("oracle", "DOC_CHECK_LOG").contains("NAME_KEY"));
        assertEquals(columns("oracle", "DOC_CHECK_LOG"), columns("mysql", "DOC_CHECK_LOG"));
    }

    @Test
    public void 자연_PK가_양쪽에_있다() throws IOException {
        String[] pks = {"(TASK_ID, NAME_KEY)", "(TASK_ID, NAME_KEY, FOUND_INST_ID, LOC_KIND, LOC_NO)", "(TASK_ID, SEQ_NO)"};
        for (String pk : pks) {
            assertTrue(pk, read("oracle").contains("PRIMARY KEY " + pk));
            assertTrue(pk, read("mysql").contains("PRIMARY KEY " + pk));
        }
    }

    @Test
    public void Oracle은_11g_문법이고_MySQL은_utf8mb4를_먼저_지정한다() throws IOException {
        String o = read("oracle");
        assertFalse(o.contains("GENERATED BY"));
        assertFalse(o.contains("FETCH FIRST"));
        assertFalse(o.contains("FOREIGN KEY"));
        String m = read("mysql");
        assertFalse(m.contains("AUTO_INCREMENT"));
        assertFalse(m.contains("FOREIGN KEY"));
        assertTrue(m.contains("SET NAMES utf8mb4;"));
    }

    @Test
    public void 파일_이름과_글_칸이_없다() throws IOException {
        for (String d : new String[]{"oracle", "mysql"}) {
            for (String t : new String[]{"DOC_CHECK", "DOC_CHECK_HIT", "DOC_CHECK_LOG"}) {
                List<String> cols = columns(d, t);
                assertFalse(cols.contains("FILE_NAME"));
                assertFalse(cols.contains("CONTEXT"));
                assertFalse(cols.contains("TEXT"));
            }
        }
    }
}
