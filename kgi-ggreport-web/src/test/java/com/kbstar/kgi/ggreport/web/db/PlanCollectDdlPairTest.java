package com.kbstar.kgi.ggreport.web.db;

import org.junit.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/** 045 DDL 쌍 — INSERT 블록 글자 그대로·두 표 칸 순서 같음·열린 요청 유일 제약·11g 문법. 파일만 읽는다(InstPlanDdlPairTest 방식). */
public class PlanCollectDdlPairTest {

    private static final Path DB = Paths.get("src/main/resources/db");
    private static final String FILE = "045_plan_collect.sql";

    private static String read(String d) throws IOException {
        Path f = DB.resolve(d).resolve(FILE);
        assertTrue(f + " 가 없다 — 작업 디렉터리가 kgi-ggreport-web/ 인지 확인", Files.exists(f));
        return new String(Files.readAllBytes(f), StandardCharsets.UTF_8);
    }

    private static List<String> inserts(String d) throws IOException {
        List<String> out = new ArrayList<>();
        boolean in = false;
        for (String line : Files.readAllLines(DB.resolve(d).resolve(FILE), StandardCharsets.UTF_8)) {
            if (line.contains("[INSERT 블록 시작")) in = true;
            else if (line.contains("[INSERT 블록 끝")) in = false;
            else if (in && line.startsWith("INSERT INTO COMMON_CODE")) out.add(line);
        }
        return out;
    }

    private static List<String> columns(String d, String table) throws IOException {
        List<String> out = new ArrayList<>();
        Set<String> skip = new HashSet<>(Arrays.asList("PRIMARY", "KEY", "CONSTRAINT", "UNIQUE", "INDEX", "FOREIGN", "CHECK"));
        Pattern word = Pattern.compile("^([A-Z][A-Z0-9_]*)\\b.*");
        boolean in = false;
        for (String raw : Files.readAllLines(DB.resolve(d).resolve(FILE), StandardCharsets.UTF_8)) {
            String line = raw.trim();
            if (line.startsWith("CREATE TABLE " + table + " (")) { in = true; continue; }
            if (!in) continue;
            if (line.startsWith(")")) break;
            Matcher m = word.matcher(line);
            if (m.matches() && !skip.contains(m.group(1))) out.add(m.group(1));
        }
        return out;
    }

    @Test
    public void INSERT_블록이_글자_그대로_같고_7행이다() throws IOException {
        List<String> o = inserts("oracle"), m = inserts("mysql");
        assertEquals(7, o.size());
        assertEquals(o, m);
    }

    @Test
    public void 감사_코드는_PLAN_ACTION_COLLECT_7개뿐이다() throws IOException {
        Set<String> codes = new TreeSet<>();
        Pattern p = Pattern.compile("VALUES \\('PLAN_ACTION', '([A-Z_]+)', ");
        for (String line : inserts("oracle")) {
            Matcher x = p.matcher(line);
            assertTrue("PLAN_ACTION 그룹만 — 새 그룹은 CommonCodeSchemaTest 를 깬다: " + line, x.find());
            codes.add(x.group(1));
        }
        assertEquals(new TreeSet<>(Arrays.asList("COLLECT_REQUEST", "COLLECT_CANCEL", "COLLECT_EXPORT", "COLLECT_RUN",
                "COLLECT_EXCLUDE", "COLLECT_FAIL", "COLLECT_APPLY")), codes);
    }

    @Test
    public void 두_표의_칸_이름과_순서가_같다() throws IOException {
        for (String t : new String[]{"PLAN_COLLECT_REQ", "PLAN_COLLECT_REQUESTER"}) {
            List<String> o = columns("oracle", t);
            assertTrue(t + " 칸을 못 읽었다", o.size() >= 6);
            assertEquals(t, o, columns("mysql", t));
        }
    }

    @Test
    public void 열린_요청_유일_제약이_양쪽에_있다() throws IOException {
        assertTrue(read("oracle").contains("CONSTRAINT UQ_PCR_OPEN UNIQUE (OPEN_INST_ID)"));
        assertTrue(read("mysql").contains("UNIQUE KEY UQ_PCR_OPEN (OPEN_INST_ID)"));
    }

    @Test
    public void Oracle은_11g_문법이고_MySQL은_utf8mb4를_먼저_지정한다() throws IOException {
        String o = read("oracle");
        assertFalse(o.contains("GENERATED BY"));
        assertFalse(o.contains("FETCH FIRST"));
        assertTrue(read("mysql").contains("SET NAMES utf8mb4;"));
    }
}
