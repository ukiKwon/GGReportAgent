-- Q18 기관장(026): 사번별 하루 열람 50 초과(건수만, 날짜는 UTC 기준 LOGGED_AT 앞 10자) / 기관당 CURRENT 둘 이상 / 머리당 ACTIVE 사진 둘 이상 / 기관 없음 / 머리 없는 칸
SELECT a.ACTOR_EMP_NO, SUBSTR(a.LOGGED_AT, 1, 10) AS DAY_UTC, COUNT(*) AS VIEWS
  FROM INST_HEAD_ACT a
 WHERE a.ACTION_CD IN ('VIEW', 'PHOTO_VIEW', 'UNMATCHED_VIEW') AND a.OUTCOME = 'OK'
 GROUP BY a.ACTOR_EMP_NO, SUBSTR(a.LOGGED_AT, 1, 10) HAVING COUNT(*) > 50;
