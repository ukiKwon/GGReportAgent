-- Q16 제안서 사전준비(024): 건 없음 / 기관 불일치 / 코드 미등록 / 대기 상태인데 요청이 PENDING 아님 / 개설 이후인데 과제 행 없음·활성 담당자 0명 / 같은 기관 활성 건 둘 이상
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE NOT EXISTS (SELECT 1 FROM BID_CASES b WHERE b.BID_CASE_ID = p.BID_CASE_ID);
SELECT p.BID_CASE_ID FROM BID_PREP p
  JOIN BID_CASES b ON b.BID_CASE_ID = p.BID_CASE_ID
 WHERE b.INSTITUTION_ID <> p.INSTITUTION_ID;
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE NOT EXISTS (SELECT 1 FROM COMMON_CODE c WHERE c.CODE_GROUP = 'PREP_STATE' AND c.CODE = p.STATE_CD);
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE p.STATE_CD = 'OPEN_PENDING'
   AND NOT EXISTS (SELECT 1 FROM APPROVAL_REQUEST r WHERE r.REQ_ID = p.OPEN_REQ_ID AND r.STATUS = 'PENDING');
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE p.STATE_CD = 'APPROVAL_PENDING'
   AND NOT EXISTS (SELECT 1 FROM APPROVAL_REQUEST r WHERE r.REQ_ID = p.PLAN_REQ_ID AND r.STATUS = 'PENDING');
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE p.STATE_CD IN ('IN_PROGRESS', 'APPROVAL_PENDING', 'WRITABLE', 'WRITING')
   AND NOT EXISTS (SELECT 1 FROM BID_PREP_TASK t WHERE t.BID_CASE_ID = p.BID_CASE_ID);
SELECT p.BID_CASE_ID FROM BID_PREP p
 WHERE p.STATE_CD IN ('IN_PROGRESS', 'APPROVAL_PENDING', 'WRITABLE', 'WRITING')
   AND NOT EXISTS (SELECT 1 FROM BID_ASSIGNMENT a WHERE a.BID_CASE_ID = p.BID_CASE_ID AND a.ACTIVE_YN = 1);
SELECT p.INSTITUTION_ID, COUNT(*) AS N FROM BID_PREP p
 WHERE p.STATE_CD IN ('CONFIRMED', 'OPEN_PENDING', 'IN_PROGRESS', 'APPROVAL_PENDING', 'WRITABLE', 'WRITING')
 GROUP BY p.INSTITUTION_ID HAVING COUNT(*) > 1;

