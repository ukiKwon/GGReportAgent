-- Q6 사번이 USERS 에 없음(결재 요청자·대결·메뉴 권한·상위 결재자)
SELECT 'AR' AS T, TO_CHAR(r.REQ_ID) AS K FROM APPROVAL_REQUEST r
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = r.REQUESTER_EMP_NO)
UNION ALL
SELECT 'AD', TO_CHAR(d.DEPUTY_ID) FROM APPROVAL_DEPUTY d
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = d.PRINCIPAL_EMP_NO)
    OR NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = d.DEPUTY_EMP_NO)
UNION ALL
SELECT 'UMP', p.EMP_NO FROM USER_MENU_PERMS p
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = p.EMP_NO)
UNION ALL
SELECT 'USR', x.EMP_NO FROM USERS x
 WHERE x.APPROVER_EMP_NO IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = x.APPROVER_EMP_NO);

-- Q7 중복(UNIQUE 를 쓰지 않는 경로에서 필수. 지금은 제약이 막으므로 0행)
