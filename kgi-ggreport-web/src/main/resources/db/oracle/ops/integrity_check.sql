SELECT SOURCE_SLUG, NOTICE_ID, COUNT(*) AS N FROM BID_CASES
 WHERE SOURCE_SLUG IS NOT NULL AND NOTICE_ID IS NOT NULL
 GROUP BY SOURCE_SLUG, NOTICE_ID HAVING COUNT(*) > 1;
SELECT REQ_ID, STEP_NO, COUNT(*) AS N FROM APPROVAL_STEP GROUP BY REQ_ID, STEP_NO HAVING COUNT(*) > 1;
SELECT RUN_ID, SEQ_NO, COUNT(*) AS N FROM ORCH_STEP GROUP BY RUN_ID, SEQ_NO HAVING COUNT(*) > 1;

