-- Q14 이사회 자료(020): 입찰 건 없음 / 기관 불일치 / 배정 머리 없음 / 활성 담당자 0명 / 코드 미등록 / 흐름·결과 불일치
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE NOT EXISTS (SELECT 1 FROM BID_CASES b WHERE b.BID_CASE_ID = m.BID_CASE_ID);
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
  JOIN BID_CASES b ON b.BID_CASE_ID = m.BID_CASE_ID
 WHERE b.INSTITUTION_ID <> m.INSTITUTION_ID;
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE NOT EXISTS (SELECT 1 FROM BID_ASSIGN_CASE c WHERE c.BID_CASE_ID = m.BID_CASE_ID);
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE NOT EXISTS (SELECT 1 FROM BID_ASSIGNMENT a WHERE a.BID_CASE_ID = m.BID_CASE_ID AND a.ACTIVE_YN = 1);
-- 자료 건의 활성 담당자 중 쓸 수 있는 사람(USERS ACTIVE ∧ 영업팀·영업팀장)이 한 명도 없는 자료 — 인계 불변식(security P1)
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE NOT EXISTS (SELECT 1 FROM BID_ASSIGNMENT a JOIN USERS u ON u.EMP_NO = a.EMP_NO
                    WHERE a.BID_CASE_ID = m.BID_CASE_ID AND a.ACTIVE_YN = 1 AND u.STATUS = 'ACTIVE'
                      AND TRIM(u.ROLE) IN ('영업팀', '영업팀장'));
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE NOT EXISTS (SELECT 1 FROM COMMON_CODE c WHERE c.CODE_GROUP = 'BOARD_STATUS' AND c.CODE = m.STATUS_CD)
    OR (m.RESULT_CD IS NOT NULL
        AND NOT EXISTS (SELECT 1 FROM COMMON_CODE c WHERE c.CODE_GROUP = 'BOARD_RESULT' AND c.CODE = m.RESULT_CD));
-- 결과는 확정된 자료에만 / 제출 중이면 요청 번호가 있어야 / 확정이면 확정 버전·확정자가 있어야
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m WHERE m.RESULT_CD IS NOT NULL AND m.STATUS_CD <> 'CONFIRMED';
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m WHERE m.STATUS_CD = 'SUBMITTED' AND (m.SUBMIT_REQ_ID IS NULL OR m.SUBMIT_SNAP IS NULL);
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE m.STATUS_CD = 'CONFIRMED' AND (m.CONFIRMED_SNAP IS NULL OR m.CONFIRMED_BY IS NULL OR m.CONFIRMED_SNAP > m.CUR_SNAP);
SELECT m.MATERIAL_ID FROM BOARD_MATERIAL m
 WHERE m.STATUS_CD = 'SUBMITTED'
   AND NOT EXISTS (SELECT 1 FROM APPROVAL_REQUEST r WHERE r.REQ_ID = m.SUBMIT_REQ_ID AND r.STATUS = 'PENDING');

