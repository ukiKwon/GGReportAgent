-- kgi-ggreport-web — Oracle 정본 스키마 (014) : 이사회 자료 양식 커스텀
--
--   BOARD_FORM       양식 헤더. 팀(TEAM_KEY = 소속 팀) 단위로 공유한다. 삭제는 STATUS=ARCHIVED 표시다.
--                    default_doc 은 코드의 수정 불가 원본이라 이 표에 없다(복제본만 담긴다).
--   BOARD_FORM_VER   양식 버전(불변 행). 편집 = 새 행 추가. SPEC_JSON 은 표 순서·제목·편집 가능한 칸 문구만
--                    담고 구조는 코드 카탈로그가 만든다(CATALOG_VER 는 저장 시점의 카탈로그 버전).
--   BOARD_FORM_USE   결재 요청이 쓴 양식 버전 기록(상신 연계는 후속 — 지금은 비어 있다).
--
-- ⚠️ 본문 JSON 에는 가상 문구만 들어간다. 개인정보·실제 수치를 넣지 않는다.
-- ⚠️ 멱등하지 않다. 008·012 적용 후 한 번만 돌린다.
-- 되돌리기(데이터 소멸 주의): DROP TABLE BOARD_FORM_USE; DROP TABLE BOARD_FORM_VER; DROP TABLE BOARD_FORM;
-- -----------------------------------------------------------------------------

CREATE TABLE BOARD_FORM (
    FORM_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TEAM_KEY     VARCHAR2(50 CHAR)  NOT NULL,
    NAME         VARCHAR2(60 CHAR)  NOT NULL,
    BASE_DOC     VARCHAR2(50 CHAR)  NOT NULL,                      -- 복제 원본(지금은 default_doc)
    STATUS       VARCHAR2(10 CHAR)  DEFAULT 'ACTIVE' NOT NULL,     -- ACTIVE / ARCHIVED
    CURRENT_VER  NUMBER(6)          DEFAULT 1 NOT NULL,            -- 낙관적 락 겸 최신 버전 번호
    CREATED_BY   VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    UPDATED_BY   VARCHAR2(7 CHAR)   NOT NULL,
    UPDATED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_FORM PRIMARY KEY (FORM_ID),
    CONSTRAINT FK_BF_CREATED FOREIGN KEY (CREATED_BY) REFERENCES USERS (EMP_NO),
    CONSTRAINT FK_BF_UPDATED FOREIGN KEY (UPDATED_BY) REFERENCES USERS (EMP_NO),
    CONSTRAINT CK_BF_STATUS CHECK (STATUS IN ('ACTIVE', 'ARCHIVED'))
);
CREATE INDEX IDX_BF_TEAM ON BOARD_FORM (TEAM_KEY, STATUS);

CREATE TABLE BOARD_FORM_VER (
    FORM_ID      NUMBER             NOT NULL,
    VER_NO       NUMBER(6)          NOT NULL,
    NAME         VARCHAR2(60 CHAR)  NOT NULL,                      -- 그 버전의 양식 이름
    CATALOG_VER  NUMBER(4)          NOT NULL,
    SPEC_JSON    CLOB               NOT NULL,                      -- 정렬·DISTINCT 대상 금지
    CREATED_BY   VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_FORM_VER PRIMARY KEY (FORM_ID, VER_NO),
    CONSTRAINT FK_BFV_FORM FOREIGN KEY (FORM_ID) REFERENCES BOARD_FORM (FORM_ID),
    CONSTRAINT FK_BFV_CREATED FOREIGN KEY (CREATED_BY) REFERENCES USERS (EMP_NO)
);

CREATE TABLE BOARD_FORM_USE (
    USE_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQ_ID       NUMBER             NOT NULL,                      -- APPROVAL_REQUEST (요청 1건당 양식 1개)
    FORM_ID      NUMBER             NOT NULL,
    VER_NO       NUMBER(6)          NOT NULL,                      -- 상신 시점 버전(이후 편집돼도 고정)
    USED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_FORM_USE PRIMARY KEY (USE_ID),
    CONSTRAINT UQ_BFU_REQ UNIQUE (REQ_ID),
    CONSTRAINT FK_BFU_REQ FOREIGN KEY (REQ_ID) REFERENCES APPROVAL_REQUEST (REQ_ID),
    CONSTRAINT FK_BFU_VER FOREIGN KEY (FORM_ID, VER_NO) REFERENCES BOARD_FORM_VER (FORM_ID, VER_NO)
);
CREATE INDEX IDX_BFU_FORM ON BOARD_FORM_USE (FORM_ID, VER_NO);
