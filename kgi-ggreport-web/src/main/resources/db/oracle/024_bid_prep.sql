CREATE TABLE PREP_TASK_DEF (
    TASK_CD      VARCHAR2(20 CHAR)  NOT NULL,
    TASK_NAME    VARCHAR2(60 CHAR)  NOT NULL,
    SORT_NO      NUMBER(4)          NOT NULL,
    KIND_CD      VARCHAR2(20 CHAR)  NOT NULL,          -- COMMON_CODE PREP_KIND: REQUIRED / OPTIONAL / CONDITIONAL
    JUDGE_CD     VARCHAR2(20 CHAR)  NOT NULL,          -- PREP_JUDGE: MANUAL(직접 체크) / FACT(사실 판정)
    FACT_KEY     VARCHAR2(30 CHAR),                    -- FACT 일 때 서버 판정기 이름: T3_FILE / RFP_ATTACH / BOARD_CONFIRMED
    PRECOND_KEY  VARCHAR2(30 CHAR),                    -- MANUAL 체크 전제 판정기(NULL = 전제 없음). 서버가 모르는 값이면 체크를 막는다
    PREREQ_CD    VARCHAR2(20 CHAR),                    -- 선행 과제(완료돼야 열림)
    COND_KEY     VARCHAR2(30 CHAR),                    -- CONDITIONAL 의 조건 판정기: RFP_REGISTERED
    READY_YN     NUMBER(1)          DEFAULT 1 NOT NULL,-- 0 = 준비중(실물 없음, 분모 제외). 정의를 실시간으로 읽는다
    ENABLED      NUMBER(1)          DEFAULT 1 NOT NULL,
    UPDATED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_PREP_TASK_DEF PRIMARY KEY (TASK_CD)
);

CREATE TABLE BID_PREP (
    BID_CASE_ID    VARCHAR2(64 CHAR)  NOT NULL,
    INSTITUTION_ID VARCHAR2(64 CHAR)  NOT NULL,        -- 잠금·조회용 사본
    STATE_CD       VARCHAR2(20 CHAR)  NOT NULL,        -- PREP_STATE
    CONFIRMED_BY   VARCHAR2(7 CHAR)   NOT NULL,        -- '제안 확정'을 누른 사람(담당자가 아님)
    CONFIRMED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    OPEN_REQ_ID    NUMBER,
    PLAN_REQ_ID    NUMBER,
    OPENED_BY      VARCHAR2(7 CHAR),                   -- 개설 승인자
    OPENED_AT      VARCHAR2(40 CHAR),
    WRITE_BY       VARCHAR2(7 CHAR),                   -- '제안서 작성하기'를 누른 담당자
    WRITE_AT       VARCHAR2(40 CHAR),
    UPDATED_BY     VARCHAR2(7 CHAR)   NOT NULL,
    UPDATED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BID_PREP PRIMARY KEY (BID_CASE_ID)
);
CREATE INDEX IDX_BP_INST ON BID_PREP (INSTITUTION_ID, STATE_CD);
CREATE INDEX IDX_BP_STATE ON BID_PREP (STATE_CD);

CREATE TABLE BID_PREP_TASK (
    BID_CASE_ID   VARCHAR2(64 CHAR)  NOT NULL,
    TASK_CD       VARCHAR2(20 CHAR)  NOT NULL,
    SORT_NO       NUMBER(4)          NOT NULL,
    KIND_CD       VARCHAR2(20 CHAR)  NOT NULL,         -- 아래 6칸은 개설 승인 때 정의에서 복사
    JUDGE_CD      VARCHAR2(20 CHAR)  NOT NULL,
    FACT_KEY      VARCHAR2(30 CHAR),
    PRECOND_KEY   VARCHAR2(30 CHAR),
    PREREQ_CD     VARCHAR2(20 CHAR),
    COND_KEY      VARCHAR2(30 CHAR),
    DONE_YN       NUMBER(1)          DEFAULT 0 NOT NULL,   -- MANUAL: 체크 / FACT: 마지막 판정값
    DONE_BY       VARCHAR2(7 CHAR),                         -- NULL = 시스템 판정
    DONE_AT       VARCHAR2(40 CHAR),
    REF_ATTACH_ID NUMBER,                                   -- T3 확정본(025 BID_PREP_ATTACH)
    REF_SHA256    VARCHAR2(64 CHAR),                        -- 지정 시점 해시
    REF_BY        VARCHAR2(7 CHAR),
    REF_AT        VARCHAR2(40 CHAR),
    CONSTRAINT PK_BID_PREP_TASK PRIMARY KEY (BID_CASE_ID, TASK_CD)
);

CREATE TABLE BID_PREP_LOG (
    LOG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BID_CASE_ID    VARCHAR2(64 CHAR)  NOT NULL,
    EVENT_CD       VARCHAR2(30 CHAR)  NOT NULL,        -- PREP_EVENT
    FROM_STATE     VARCHAR2(20 CHAR),
    TO_STATE       VARCHAR2(20 CHAR),
    TASK_CD        VARCHAR2(20 CHAR),
    ATTACH_ID      NUMBER,                              -- T3 지정이면 '이후' 첨부(025 이후)
    FROM_ATTACH_ID NUMBER,                              -- T3 변경의 '이전' 첨부
    REQ_ID         NUMBER,
    REASON         VARCHAR2(200 CHAR),                  -- 확정 취소·반려·중단 등 사유(서버가 개인정보 검사한 글). 비면 NULL
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),                    -- NULL = 시스템
    EMP_VERIFIED   NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BID_PREP_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_BPL_CASE ON BID_PREP_LOG (BID_CASE_ID, LOG_ID);

CREATE TABLE BID_PREP_ACT (
    ACT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BID_CASE_ID  VARCHAR2(64 CHAR)  NOT NULL,
    ACTION_CD    VARCHAR2(30 CHAR)  NOT NULL,          -- VIEW / HISTORY / CHECK / UNCHECK / ... (PREP_EVENT 와 별개)
    OUTCOME      VARCHAR2(20 CHAR)  NOT NULL,          -- OK / DENIED / HIDDEN / BLOCKED / INVALID / ERROR
    STATE_CD     VARCHAR2(20 CHAR)  NOT NULL,          -- 행위 직전 건 상태(건이 없으면 NONE)
    TASK_CD      VARCHAR2(20 CHAR),
    ATTACH_ID    NUMBER,
    ACTOR_EMP_NO VARCHAR2(7 CHAR),
    EMP_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID    VARCHAR2(30 CHAR)  NOT NULL,          -- 허용 목록 밖은 UNKNOWN
    BUTTON_ID    VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID     NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT    VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BID_PREP_ACT PRIMARY KEY (ACT_ID)
);
CREATE INDEX IDX_BPA_CASE ON BID_PREP_ACT (BID_CASE_ID, ACT_ID);
CREATE INDEX IDX_BPA_ACTOR ON BID_PREP_ACT (ACTOR_EMP_NO, ACT_ID);

