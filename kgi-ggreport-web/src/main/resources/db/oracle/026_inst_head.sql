CREATE TABLE INST_HEAD (                              -- 사람 x 재임 1행
    HEAD_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID   VARCHAR2(64 CHAR),                 -- NULL = 매칭 대기(반입 후보)
    SRC_ORG_CD       VARCHAR2(20 CHAR),                 -- 수집 쪽이 보낸 기관코드 원문(매칭 보조)
    SRC_ORG_NAME     VARCHAR2(100 CHAR),                -- 수집 쪽이 보낸 기관명(매칭 보조)
    STATUS_CD        VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_STATUS
    ORIGIN_CD        VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_ORIGIN
    BATCH_ID         VARCHAR2(64 CHAR),
    CREATED_BY       VARCHAR2(7 CHAR)   NOT NULL,       -- 직접 입력자 또는 반입 버튼을 누른 사람
    CREATED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    CREATED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    DECIDED_BY       VARCHAR2(7 CHAR),                  -- 확정·기각한 사람
    DECIDED_AT       VARCHAR2(40 CHAR),
    ENDED_BY         VARCHAR2(7 CHAR),                  -- CURRENT -> FORMER 로 내린 사람(교체 확정자)
    ENDED_AT         VARCHAR2(40 CHAR),
    MATCHED_BY       VARCHAR2(7 CHAR),                  -- 매칭 대기 -> 기관 지정한 사람(U3)
    MATCHED_AT       VARCHAR2(40 CHAR),
    MERGED_INTO_ID   NUMBER,                            -- STATUS MERGED 일 때 칸을 넘겨받은 현 기관장 HEAD_ID
    CONSTRAINT PK_INST_HEAD PRIMARY KEY (HEAD_ID)
);
CREATE INDEX IDX_IH_INST ON INST_HEAD (INSTITUTION_ID, STATUS_CD);
CREATE INDEX IDX_IH_STATUS ON INST_HEAD (STATUS_CD, HEAD_ID);

CREATE TABLE INST_HEAD_ITEM (                         -- 칸 값 1개 = 1행(후보·확정·대체 모두). 출처는 행마다
    ITEM_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    HEAD_ID          NUMBER             NOT NULL,
    INSTITUTION_ID   VARCHAR2(64 CHAR),                 -- 머리의 사본(묶음 조회용). 매칭 대기면 NULL
    FIELD_CD         VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_FIELD
    STATE_CD         VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_ITEM_STATE
    ORIGIN_CD        VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_ORIGIN
    BATCH_ID         VARCHAR2(64 CHAR),
    VAL_TEXT         VARCHAR2(60 CHAR),                 -- NAME(30)·POSITION(40)·EDU·CAREER(60) 한 줄
    VAL_DATE         VARCHAR2(10 CHAR),                 -- FIRST_TAKE_OFFICE·TERM_START·TERM_END: YYYY-MM-DD
    VAL_FROM         VARCHAR2(7 CHAR),                  -- CAREER 시작 YYYY 또는 YYYY-MM
    VAL_TO           VARCHAR2(7 CHAR),                  -- CAREER 끝 / EDU 졸업연도. NULL = 현재·미상
    VAL_FLAG         NUMBER(1),                         -- ACTING: 1 권한대행 / 0 아님
    SRC_KIND_CD      VARCHAR2(20 CHAR)  NOT NULL,       -- HEAD_SRC
    SRC_TITLE        VARCHAR2(100 CHAR) NOT NULL,       -- 문서명·기사명·누리집 쪽 이름
    SRC_URL          VARCHAR2(1000 CHAR),               -- http/https 만, 계정정보 금지. 서버는 열지 않는다
    SRC_PUBLISHED    VARCHAR2(10 CHAR),                 -- 보도·게시일(있으면)
    CHECKED_ON       VARCHAR2(10 CHAR)  NOT NULL,       -- 확인일
    CREATED_BY       VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    CREATED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    DECIDED_BY       VARCHAR2(7 CHAR),
    DECIDED_AT       VARCHAR2(40 CHAR),
    SUPERSEDED_BY_ID NUMBER,                            -- 이 값을 대체한 ITEM_ID
    VOIDED_BY        VARCHAR2(7 CHAR),
    VOIDED_AT        VARCHAR2(40 CHAR),
    CONSTRAINT PK_INST_HEAD_ITEM PRIMARY KEY (ITEM_ID)
);
CREATE INDEX IDX_IHI_HEAD ON INST_HEAD_ITEM (HEAD_ID, FIELD_CD, STATE_CD);
CREATE INDEX IDX_IHI_INST ON INST_HEAD_ITEM (INSTITUTION_ID, STATE_CD);

CREATE TABLE INST_HEAD_PHOTO (                        -- 서버가 다시 만든 JPEG 만 보관(원본·EXIF·원래 파일 이름 미보관)
    PHOTO_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    HEAD_ID           NUMBER             NOT NULL,
    INSTITUTION_ID    VARCHAR2(64 CHAR)  NOT NULL,
    STATE_CD          VARCHAR2(20 CHAR)  NOT NULL,      -- HEAD_PHOTO_STATE
    STORE_KEY         VARCHAR2(40 CHAR)  NOT NULL,      -- 서버 32자리 16진수
    SHA256            VARCHAR2(64 CHAR)  NOT NULL,      -- 저장본 해시(읽을 때 다시 대조)
    ORIG_SHA256       VARCHAR2(64 CHAR)  NOT NULL,      -- 올라온 원본 해시(추적용, 원본은 버림)
    ORIG_EXT          VARCHAR2(10 CHAR)  NOT NULL,      -- jpg / png
    SIZE_BYTES        NUMBER(12)         NOT NULL,
    IMG_W             NUMBER(5)          NOT NULL,
    IMG_H             NUMBER(5)          NOT NULL,
    LICENSE_CD        VARCHAR2(20 CHAR)  NOT NULL,      -- PHOTO_LICENSE(ENABLED=1 인 것만 받는다)
    SRC_KIND_CD       VARCHAR2(20 CHAR)  NOT NULL,
    SRC_TITLE         VARCHAR2(100 CHAR) NOT NULL,
    SRC_URL           VARCHAR2(1000 CHAR),
    CHECKED_ON        VARCHAR2(10 CHAR)  NOT NULL,      -- 이용 조건 확인일
    UPLOADED_BY       VARCHAR2(7 CHAR)   NOT NULL,      -- = 이용 조건 확인자
    UPLOADED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    UPLOADED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    ENDED_BY          VARCHAR2(7 CHAR),                 -- 교체·무효 처리한 사람(복원되면 비운다 — 이력은 LOG)
    ENDED_AT          VARCHAR2(40 CHAR),
    CONSTRAINT PK_INST_HEAD_PHOTO PRIMARY KEY (PHOTO_ID)
);
CREATE INDEX IDX_IHP_HEAD ON INST_HEAD_PHOTO (HEAD_ID, STATE_CD);
CREATE INDEX IDX_IHP_INST ON INST_HEAD_PHOTO (INSTITUTION_ID, PHOTO_ID);

CREATE TABLE INST_HEAD_LOG (                          -- 업무 이력(추가 전용)
    LOG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID VARCHAR2(64 CHAR),
    HEAD_ID        NUMBER,
    EVENT_CD       VARCHAR2(30 CHAR)  NOT NULL,         -- HEAD_EVENT
    ITEM_ID        NUMBER,
    FROM_ITEM_ID   NUMBER,                              -- 대체된 이전 값
    PHOTO_ID       NUMBER,
    FROM_PHOTO_ID  NUMBER,
    FROM_HEAD_ID   NUMBER,                              -- 교체로 FORMER 가 된 기관장 / 합쳐진 후보 머리
    BATCH_ID       VARCHAR2(64 CHAR),
    REASON         VARCHAR2(200 CHAR),                  -- 기각·무효 사유(서버가 개인정보·금지 패턴 검사). 칸 값 원문 금지
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),
    ACTOR_ROLE     VARCHAR2(20 CHAR),                   -- 처리 시점 USERS.ROLE(부장 대리 처리 식별)
    SELF_FLAG      NUMBER(1)          DEFAULT 0 NOT NULL, -- 1 = 처리자가 대상 후보를 낸 사람(반입자 포함)
    EMP_VERIFIED   NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_INST_HEAD_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_IHL_INST ON INST_HEAD_LOG (INSTITUTION_ID, LOG_ID);
CREATE INDEX IDX_IHL_EVENT ON INST_HEAD_LOG (EVENT_CD, LOG_ID);

CREATE TABLE INST_HEAD_ACT (                          -- 열람·행위 감사(BID_PREP_ACT 와 같은 모양, 추가 전용)
    ACT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID VARCHAR2(64 CHAR)  NOT NULL,         -- 기관 밖 행위·형식 밖이면 'NONE'
    HEAD_ID        NUMBER,
    ACTION_CD      VARCHAR2(30 CHAR)  NOT NULL,
    OUTCOME        VARCHAR2(20 CHAR)  NOT NULL,         -- OK / DENIED / HIDDEN / BLOCKED / INVALID / BUSY / ERROR
    TARGET_ID      NUMBER,                              -- ITEM_ID 또는 PHOTO_ID(숫자 형식일 때만)
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),
    EMP_VERIFIED   NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID      VARCHAR2(30 CHAR)  NOT NULL,
    BUTTON_ID      VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID       NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_INST_HEAD_ACT PRIMARY KEY (ACT_ID)
);
CREATE INDEX IDX_IHA_INST ON INST_HEAD_ACT (INSTITUTION_ID, ACT_ID);
CREATE INDEX IDX_IHA_ACTOR ON INST_HEAD_ACT (ACTOR_EMP_NO, LOGGED_AT);

