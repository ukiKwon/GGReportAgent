-- 외래키·CHECK·UNIQUE 없음(PK 와 조회용 인덱스만). 참조는 서비스가 확인한다:
--   INSTITUTION_ID -> INSTITUTIONS, HEAD_ID·MERGED_INTO_ID·FROM_HEAD_ID -> INST_HEAD, *ITEM_ID -> INST_HEAD_ITEM,
--   *PHOTO_ID -> INST_HEAD_PHOTO, *_BY·ACTOR_EMP_NO -> USERS, *_CD -> COMMON_CODE.
-- 허용 칸만 둔다: 이름·직위·권한대행·첫 취임일·현 임기 시작일·임기 만료일·학력·경력. 자유 서술·연락처·경조사 칸 없음.
--   정당 직책·범죄 경력·건강·종교·가족·경조사·전화번호는 서버가 입력 단계에서 거부한다(저장 안 함, 사용자 결정 2026-11-11).
-- 행을 지우지 않는다: 이전 기관장 FORMER(화면 숨김), 합친 후보 MERGED, 바뀐 값 SUPERSEDED, 옛 사진 REPLACED, 무효 VOIDED.
--   보존 기간 뒤 삭제는 NEXT 35(미정) — 별도 배치 계정이 한다.
-- 사진 본체는 디스크(설정 ggreport.inst-head.photo-dir, 운영은 웹 루트 밖 절대경로). DB 와 함께 백업 대상(같은 보존 규칙).
-- 서버는 SRC_URL 을 열지 않는다(미리보기·검증 요청 없음). 화면 링크 표시용 문자열일 뿐이다.
-- ⚠️ 사번·화면·버튼은 자기신고(X-Emp-No 등)다. *_VERIFIED·EMP_VERIFIED=0 이면 '검증됨'으로 표시하지 않는다.
-- ⚠️ DB 권한(DBA): 앱 계정은 INST_HEAD·INST_HEAD_ITEM·INST_HEAD_PHOTO 에 SELECT·INSERT·UPDATE 만,
--   INST_HEAD_LOG·INST_HEAD_ACT 에 SELECT·INSERT 만 준다(다섯 표 모두 DELETE 없음, LOG·ACT 는 UPDATE 도 없음).
-- ⚠️ 멱등하지 않다. 016(COMMON_CODE)·025 이후 한 번만 돌린다.
-- 되돌리기(데이터 소멸, 운영 금지 — 운영은 설정 ggreport.inst-head.enabled=false 로 끈다):
--   DROP TABLE INST_HEAD_ACT; DROP TABLE INST_HEAD_LOG; DROP TABLE INST_HEAD_PHOTO; DROP TABLE INST_HEAD_ITEM; DROP TABLE INST_HEAD;
--   DELETE FROM COMMON_CODE WHERE CODE_GROUP IN ('HEAD_STATUS','HEAD_ORIGIN','HEAD_FIELD','HEAD_ITEM_STATE',
--     'HEAD_SRC','HEAD_PHOTO_STATE','PHOTO_LICENSE','HEAD_EVENT');
