CREATE TABLE INST_NEWS_IMPORT (                      -- 반입 1건 = 판 1개
    IMPORT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID    VARCHAR2(64 CHAR)  NOT NULL,
    FILE_DATE         VARCHAR2(10 CHAR)  NOT NULL,      -- 파일 이름 날짜 = 확인일 중 가장 늦은 날
    FILE_SHA256       VARCHAR2(64 CHAR)  NOT NULL,
    FILE_BYTES        NUMBER(12)         NOT NULL,
    ITEM_COUNT        NUMBER(3)          NOT NULL,      -- 1~10
    BATCH_ID          VARCHAR2(64 CHAR),
    IMPORTED_BY       VARCHAR2(7 CHAR)   NOT NULL,
    IMPORTED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    IMPORTED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    CONSTRAINT PK_INST_NEWS_IMPORT PRIMARY KEY (IMPORT_ID)
);
CREATE INDEX IDX_INI_INST ON INST_NEWS_IMPORT (INSTITUTION_ID, IMPORT_ID);
CREATE INDEX IDX_INI_SHA ON INST_NEWS_IMPORT (INSTITUTION_ID, FILE_SHA256);

CREATE TABLE INST_NEWS_ITEM (                        -- 기사 1건 = 1행
    NEWS_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    IMPORT_ID       NUMBER              NOT NULL,
    INSTITUTION_ID  VARCHAR2(64 CHAR)   NOT NULL,
    ROW_NO          NUMBER(6)           NOT NULL,       -- 파일 행 번호(빈 줄 포함 원시 행, 머리행 다음 = 1)
    FIELD_CD        VARCHAR2(20 CHAR)   NOT NULL,       -- TREASURY / FINANCE / BUDGET / MAJOR_PROJECT / HEAD_NEWS (서버 상수, 코드표 없음)
    TITLE           VARCHAR2(200 CHAR)  NOT NULL,
    PRESS           VARCHAR2(60 CHAR)   NOT NULL,
    PUBLISHED_ON    VARCHAR2(10 CHAR)   NOT NULL,       -- yyyy-MM-dd, 확인일 이전 1년 안
    SRC_URL         VARCHAR2(1000 CHAR) NOT NULL,       -- http/https. 서버는 열지 않는다
    SUMMARY         VARCHAR2(900 CHAR)  NOT NULL,       -- 직접 쓴 요약(300자 + 줄바꿈 여유)
    CHECKED_ON      VARCHAR2(10 CHAR)   NOT NULL,
    COLLECTOR_AGENT VARCHAR2(60 CHAR)   NOT NULL,       -- 수집 프로그램 식별자(사람 정보 없음)
    CONSTRAINT PK_INST_NEWS_ITEM PRIMARY KEY (NEWS_ID)
);
CREATE INDEX IDX_INW_IMPORT ON INST_NEWS_ITEM (IMPORT_ID, ROW_NO);

