ALTER TABLE INSTITUTIONS ADD (
    ORG_CODE               VARCHAR2(20 CHAR),
    G2B_CODE               VARCHAR2(20 CHAR),
    OP_STATUS              VARCHAR2(20 CHAR)  DEFAULT 'OPERATING' NOT NULL,
    OPEN_DATE              VARCHAR2(10 CHAR),
    CONTRACT_END_CONFIRMED NUMBER(1)          DEFAULT 0 NOT NULL,
    CONTRACT_END_SRC_URL   VARCHAR2(500 CHAR),
    CONTRACT_END_SRC_NO    VARCHAR2(50 CHAR),
    OP_SRC_URL             VARCHAR2(500 CHAR),
    OP_SRC_NO              VARCHAR2(50 CHAR)
);
CREATE INDEX IDX_INST_ORG ON INSTITUTIONS (ORG_CODE);
CREATE INDEX IDX_INST_G2B ON INSTITUTIONS (G2B_CODE);

CREATE TABLE INST_EDIT_LOG (                          -- 기관 편집 이력(추가 전용). 변경된 칸 1개 = 1행, 한 번의 저장은 BATCH_KEY 로 묶음
    LOG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BATCH_KEY      VARCHAR2(36 CHAR)  NOT NULL,
    INSTITUTION_ID VARCHAR2(64 CHAR)  NOT NULL,
    FIELD_CD       VARCHAR2(30 CHAR)  NOT NULL,         -- REGION_CODE·TYPE·LAST_BID·TERM·CONTRACT_END·CONTRACT_END_CONFIRMED·OP_STATUS·OPEN_DATE
    OLD_VAL        VARCHAR2(60 CHAR),
    NEW_VAL        VARCHAR2(60 CHAR),
    SRC_URL        VARCHAR2(500 CHAR),                  -- 확정·상태 변경에 붙인 출처
    SRC_NO         VARCHAR2(50 CHAR),
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),
    EMP_VERIFIED   NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID      VARCHAR2(30 CHAR)  NOT NULL,
    BUTTON_ID      VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID       NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_INST_EDIT_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_IEL_INST ON INST_EDIT_LOG (INSTITUTION_ID, LOG_ID);
CREATE INDEX IDX_IEL_ACTOR ON INST_EDIT_LOG (ACTOR_EMP_NO, LOGGED_AT);

