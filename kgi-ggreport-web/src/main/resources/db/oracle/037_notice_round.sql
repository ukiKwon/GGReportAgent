CREATE TABLE NOTICE_ROUND (
    INSTITUTION_ID   VARCHAR2(64 CHAR)  NOT NULL,
    ROUND_SEQ        NUMBER(6)          NOT NULL,   -- 기관 안에서 1,2,3…
    SOURCE_CD        VARCHAR2(20 CHAR)  NOT NULL,   -- NOTICE_ROUND_SRC(1차 INST_DATA)
    ANCHOR_LAST_BID  VARCHAR2(30 CHAR),             -- 회차를 열 때 서버가 읽은 INSTITUTIONS.LAST_BID
    TARGET_TERM_YEAR NUMBER(4),                     -- 대상 약정 시작 연도(모르면 NULL, 근거 없이 채우지 않음)
    OPENED_AT        VARCHAR2(40 CHAR)  NOT NULL,
    OPENED_BY        VARCHAR2(7 CHAR)   NOT NULL,
    CLOSED_AT        VARCHAR2(40 CHAR),             -- NULL = 열림
    CLOSE_REASON_CD  VARCHAR2(20 CHAR),             -- NOTICE_ROUND_CLOSE
    CLOSED_BY        VARCHAR2(7 CHAR),              -- 닫힘을 일으킨 저장의 처리자
    CLOSED_LAST_BID  VARCHAR2(30 CHAR),             -- 닫을 때 읽은 LAST_BID
    CONSTRAINT PK_NOTICE_ROUND PRIMARY KEY (INSTITUTION_ID, ROUND_SEQ)
);
CREATE INDEX IDX_NR_OPEN ON NOTICE_ROUND (CLOSED_AT, INSTITUTION_ID);

CREATE TABLE NOTICE_ROUND_LOG (
    INSTITUTION_ID     VARCHAR2(64 CHAR)  NOT NULL,
    ROUND_SEQ          NUMBER(6)          NOT NULL,
    REV_NO             NUMBER(6)          NOT NULL,  -- 회차 안에서 1부터 연속
    STATUS_CD          VARCHAR2(20 CHAR)  NOT NULL,  -- NOTICE_STATUS(IN_PROGRESS/CLOSED/DELAYED)
    PREV_STATUS_CD     VARCHAR2(20 CHAR),            -- NULL = 첫 기록
    OPINION            VARCHAR2(500 CHAR),
    NEXT_CHECK_DATE    VARCHAR2(10 CHAR),            -- YYYY-MM-DD(한국 날짜)
    PREV_NEXT_CHECK    VARCHAR2(10 CHAR),
    ACTIVE_PREP        NUMBER(1)          DEFAULT 0 NOT NULL,  -- 저장 때 진행 중 제안이 있었나(서버가 BID_PREP 에서 셈)
    ACTIVE_PREP_STATE  VARCHAR2(30 CHAR),
    SNAP_DUE_DATE      VARCHAR2(10 CHAR),
    SNAP_DUE_BASIS     VARCHAR2(20 CHAR),            -- NOTICE_DUE_BASIS
    SNAP_DUE_CONFIRMED NUMBER(1)          DEFAULT 0 NOT NULL,
    SNAP_AUTO_KIND     VARCHAR2(20 CHAR),            -- NOTICE_AUTO_KIND
    SNAP_AUTO_DAYS     NUMBER(6),                    -- 오늘 - 예정일(일). 음수 = 예정일 전
    SNAP_LAST_BID      VARCHAR2(30 CHAR),            -- 저장 때 서버가 읽은 LAST_BID
    HANDLER_EMP_NO     VARCHAR2(7 CHAR)   NOT NULL,
    HANDLER_NAME       VARCHAR2(50 CHAR)  NOT NULL,  -- 그때 이름 스냅샷
    EMP_VERIFIED       NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID          VARCHAR2(30 CHAR)  NOT NULL,
    BUTTON_ID          VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID           NUMBER(1)          DEFAULT 0 NOT NULL,
    HANDLED_AT         VARCHAR2(40 CHAR)  NOT NULL,  -- Times.nowIso
    CONSTRAINT PK_NOTICE_ROUND_LOG PRIMARY KEY (INSTITUTION_ID, ROUND_SEQ, REV_NO)
);
CREATE INDEX IDX_NRL_STATUS  ON NOTICE_ROUND_LOG (STATUS_CD, NEXT_CHECK_DATE);
CREATE INDEX IDX_NRL_HANDLER ON NOTICE_ROUND_LOG (HANDLER_EMP_NO, HANDLED_AT);

