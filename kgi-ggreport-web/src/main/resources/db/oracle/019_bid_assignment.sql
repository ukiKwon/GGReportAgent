CREATE TABLE BID_ASSIGN_CASE (
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    GROUP_VER       NUMBER(6)          DEFAULT 1 NOT NULL,   -- 담당자 집합이 바뀔 때마다 +1(동시 변경 충돌 방지)
    PENDING_REQ_ID  NUMBER,                                  -- 진행 중인 담당자 변경 결재 요청(없으면 NULL)
    CREATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    UPDATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    UPDATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BID_ASSIGN_CASE PRIMARY KEY (BID_CASE_ID)
);

CREATE TABLE BID_ASSIGNMENT (
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    EMP_NO          VARCHAR2(7 CHAR)   NOT NULL,
    ACTIVE_YN       NUMBER(1)          DEFAULT 1 NOT NULL,   -- 1 = 현재 담당, 0 = 해제됨
    ASSIGNED_BY     VARCHAR2(7 CHAR)   NOT NULL,
    ASSIGNED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    RELEASED_BY     VARCHAR2(7 CHAR),
    RELEASED_AT     VARCHAR2(40 CHAR),
    CONSTRAINT PK_BID_ASSIGNMENT PRIMARY KEY (BID_CASE_ID, EMP_NO)
);
CREATE INDEX IDX_BA_EMP ON BID_ASSIGNMENT (EMP_NO, ACTIVE_YN);

CREATE TABLE BID_ASSIGN_LOG (
    LOG_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    ACTION_CD       VARCHAR2(10 CHAR)  NOT NULL,   -- COMMON_CODE ASSIGN_ACTION (ASSIGN/ADD/RELEASE)
    TARGET_EMP_NO   VARCHAR2(7 CHAR)   NOT NULL,   -- 배정·해제 대상 사번
    REQ_ID          NUMBER,                        -- 담당자 변경 결재 요청 번호(최초 배정이면 NULL)
    REASON          VARCHAR2(200 CHAR),            -- 비면 NULL(Oracle 은 빈 문자열을 NULL 로 본다), 앱이 빈 문자열로 정규화
    ACTOR_EMP_NO    VARCHAR2(7 CHAR)   NOT NULL,   -- 수행·승인한 사번(서버가 Actor 에서)
    EMP_VERIFIED    NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BID_ASSIGN_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_BAL_CASE ON BID_ASSIGN_LOG (BID_CASE_ID, LOG_ID);

