-- -----------------------------------------------------------------------------
-- kgi-ggreport-web — 스키마 (012) : 결재 — 대결 지정, 결재 요청·단계
--
--   APPROVAL_DEPUTY   결재자(PRINCIPAL)가 부재 기간(START~END) 동안 자기 결재를 대신하게 하는 지정.
--                     **결재자 본인이 지정**하고 관리자(master)는 조회·취소할 수 있다. 취소는 삭제가 아니라
--                     CANCELLED_AT 표시다(이력 보존).
--   APPROVAL_REQUEST  결재 요청 1건. 유형(REQ_TYPE)별 내용은 PAYLOAD(JSON 문자열)에 담는다.
--                     상태 PENDING / APPROVED / REJECTED / CANCELLED.
--   APPROVAL_STEP     요청의 결재 단계. **상신 시점의 결재선을 스냅샷**으로 고정한다(이후 상위 결재자가
--                     바뀌어도 진행 중인 건은 안 바뀐다). 추가 전용 — 처리 결과만 갱신하고 지우지 않는다.
--                     KIND = LINE(지정된 결재자) / ADMIN(시스템 관리자 누구나).
--
-- ⚠️ 결재 방향 규칙은 서버 코드(Ranks.mayDecide)가 정한다: 상신자의 직급이 처리자(결재자·대결자)보다
--    **높으면** 결재할 수 없다(상위 직급자가 하위 직급자에게 결재를 올리는 결과가 되므로). 그 밖의
--    대결자 자격(직급 등)은 고정하지 않는다.
-- ⚠️ 컬럼명에 Oracle 예약어(COMMENT, TO_DATE 등)를 쓰지 않는다.
-- ⚠️ 멱등하지 않다. 010 적용 후 한 번만 돌린다.
-- -----------------------------------------------------------------------------

CREATE TABLE APPROVAL_DEPUTY (
    DEPUTY_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PRINCIPAL_EMP_NO VARCHAR2(7 CHAR)   NOT NULL,                -- 결재자(부재하는 사람)
    DEPUTY_EMP_NO    VARCHAR2(7 CHAR)   NOT NULL,                -- 대결자
    START_DATE       VARCHAR2(10 CHAR)  NOT NULL,                -- YYYY-MM-DD (한국 날짜)
    END_DATE         VARCHAR2(10 CHAR)  NOT NULL,
    REASON           VARCHAR2(200 CHAR),
    CREATED_BY       VARCHAR2(7 CHAR),
    CREATED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    CANCELLED_AT     VARCHAR2(40 CHAR),
    CANCELLED_BY     VARCHAR2(7 CHAR),
    CONSTRAINT PK_APPROVAL_DEPUTY PRIMARY KEY (DEPUTY_ID),
    CONSTRAINT FK_AD_PRINCIPAL FOREIGN KEY (PRINCIPAL_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT FK_AD_DEPUTY FOREIGN KEY (DEPUTY_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT CK_AD_NOT_SELF CHECK (PRINCIPAL_EMP_NO <> DEPUTY_EMP_NO)
);
CREATE INDEX IDX_AD_PRINCIPAL ON APPROVAL_DEPUTY (PRINCIPAL_EMP_NO);
CREATE INDEX IDX_AD_DEPUTY ON APPROVAL_DEPUTY (DEPUTY_EMP_NO);

CREATE TABLE APPROVAL_REQUEST (
    REQ_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQ_TYPE         VARCHAR2(30 CHAR)  NOT NULL,                -- ApprovalTypes 의 키(PERM_REQUEST …)
    REQUESTER_EMP_NO VARCHAR2(7 CHAR)   NOT NULL,
    TITLE            VARCHAR2(200 CHAR) NOT NULL,
    PAYLOAD          VARCHAR2(4000 CHAR),                        -- 유형별 JSON(권한 신청: 사유 + 메뉴별 변경)
    STATUS           VARCHAR2(20 CHAR)  DEFAULT 'PENDING' NOT NULL,
    CURRENT_STEP     NUMBER(2)          DEFAULT 1 NOT NULL,
    RESULT_NOTE      VARCHAR2(300 CHAR),                         -- 반영 결과·취소 사유 등
    CREATED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    DECIDED_AT       VARCHAR2(40 CHAR),
    CONSTRAINT PK_APPROVAL_REQUEST PRIMARY KEY (REQ_ID),
    CONSTRAINT FK_AR_REQUESTER FOREIGN KEY (REQUESTER_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT CK_AR_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX IDX_AR_REQUESTER ON APPROVAL_REQUEST (REQUESTER_EMP_NO, REQ_ID);
CREATE INDEX IDX_AR_STATUS ON APPROVAL_REQUEST (STATUS, REQ_ID);

CREATE TABLE APPROVAL_STEP (
    STEP_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQ_ID           NUMBER             NOT NULL,
    STEP_NO          NUMBER(2)          NOT NULL,
    KIND             VARCHAR2(10 CHAR)  NOT NULL,                -- LINE / ADMIN
    APPROVER_EMP_NO  VARCHAR2(7 CHAR),                           -- LINE 이면 지정된 결재자, ADMIN 이면 NULL
    STATUS           VARCHAR2(20 CHAR)  DEFAULT 'PENDING' NOT NULL, -- PENDING / APPROVED / REJECTED / SKIPPED
    ACTED_BY         VARCHAR2(7 CHAR),                           -- 실제 처리한 사람(대결이면 대결자)
    ACTED_AS_DEPUTY  NUMBER(1)          DEFAULT 0 NOT NULL,
    COMMENT_TEXT     VARCHAR2(500 CHAR),
    ACTED_AT         VARCHAR2(40 CHAR),
    CONSTRAINT PK_APPROVAL_STEP PRIMARY KEY (STEP_ID),
    CONSTRAINT UQ_AS_REQ_STEP UNIQUE (REQ_ID, STEP_NO),
    CONSTRAINT FK_AS_REQ FOREIGN KEY (REQ_ID) REFERENCES APPROVAL_REQUEST (REQ_ID),
    CONSTRAINT CK_AS_KIND CHECK (KIND IN ('LINE', 'ADMIN')),
    CONSTRAINT CK_AS_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'SKIPPED'))
);
CREATE INDEX IDX_AS_APPROVER ON APPROVAL_STEP (APPROVER_EMP_NO, STATUS);
