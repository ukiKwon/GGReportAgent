-- kgi-ggreport-web — Oracle 정본 스키마 (008) : 시스템 관리 — 사용자(사번)·메뉴별 권한·접근 이력
-- ⚠️ 이 파일이 **정본**이다. db/mysql/008_system_admin.sql 은 외부망 로컬 전용 미러다.
--
-- ── 무엇이 들어 있나 ────────────────────────────────────────────────────────────
--   USERS            사용자. 사번(7자리 숫자)이 키. 결재 등급(팀장급·부장급·대표급).
--   USER_MENU_PERMS  사용자별 메뉴 권한 **예외**. 역할 기본값(ROLE_MENUS·앱 기본 격자) 위에 얹는다.
--                    메뉴 권한을 받으면 조회(CAN_VIEW)가 기본. 작성·수정·결재는 기본 꺼짐.
--                    결재(CAN_APPROVE)는 결재 개념이 확인된 메뉴(결재함·작업함)에서만 켤 수 있다
--                    — 판정은 서버 코드(MenuPerms.APPROVABLE)가 하고, 모르는 메뉴는 꺼 둔다.
--   ACCESS_LOG       접근 이력(보안 감사). **추가 전용** — 앱 DB 계정에는 INSERT/SELECT 만 주고
--                    UPDATE/DELETE 는 주지 않는 것을 권장한다. 본문·비밀번호·쿼리값은 넣지 않는다.
--   PERM_CHANGE_LOG  "누가 누구의 권한을 어떻게 바꿨나". 권한 변경과 **같은 트랜잭션**에 기록한다.
--
-- ⚠️ 신원은 아직 자기신고다(서버 인증 없음). ACCESS_LOG.EMP_VERIFIED=1 은 앞단(WebSphere/SSO)이 준
--    인증 주체를 받은 경우이고, 0 이면 화면이 보낸 사번을 그대로 적은 것이다. 0 인 행은 위조 가능.
-- ⚠️ 보존 기간은 사내 보안 규정을 따른다(기본 가정 1년, 별도 배치로 이관·삭제). 이 스크립트는 지우지 않는다.
-- ⚠️ 시각은 본체와 같은 ISO 문자열(Times.nowIso)이다.
-- ⚠️ 멱등하지 않다. 001~007 적용 후 한 번만 돌린다.
-- -----------------------------------------------------------------------------

CREATE TABLE USERS (
    EMP_NO         VARCHAR2(7 CHAR)   NOT NULL,                 -- 사번: 숫자 7자리
    NAME           VARCHAR2(50 CHAR)  NOT NULL,
    ROLE           VARCHAR2(50 CHAR)  NOT NULL,                 -- Teams.ROLES 중 하나(영업팀장·전산팀 …)
    POSITION_TITLE VARCHAR2(50 CHAR),                           -- 직위 표시용(사원·대리·과장 …)
    APPROVAL_GRADE VARCHAR2(20 CHAR)  DEFAULT 'NONE'   NOT NULL, -- NONE / TEAM_LEAD(팀장급) / DEPT_HEAD(부장급) / EXECUTIVE(대표급)
    STATUS         VARCHAR2(20 CHAR)  DEFAULT 'ACTIVE' NOT NULL, -- ACTIVE / LOCKED / RETIRED(삭제 대신 퇴직 처리)
    FAILED_LOGINS  NUMBER(3)          DEFAULT 0        NOT NULL,
    LAST_LOGIN_AT  VARCHAR2(40 CHAR),
    CREATED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    UPDATED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (EMP_NO),
    CONSTRAINT CK_USERS_EMP_NO CHECK (REGEXP_LIKE(EMP_NO, '^[0-9]{7}$')),
    CONSTRAINT CK_USERS_GRADE  CHECK (APPROVAL_GRADE IN ('NONE', 'TEAM_LEAD', 'DEPT_HEAD', 'EXECUTIVE')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'RETIRED'))
);

CREATE TABLE USER_MENU_PERMS (
    EMP_NO      VARCHAR2(7 CHAR)  NOT NULL,
    MENU_KEY    VARCHAR2(50 CHAR) NOT NULL,                      -- Menus.MENU_KEYS 와 같은 키
    CAN_VIEW    NUMBER(1) DEFAULT 1 NOT NULL,                    -- 메뉴 권한 = 조회가 기본
    CAN_WRITE   NUMBER(1) DEFAULT 0 NOT NULL,                    -- 작성
    CAN_EDIT    NUMBER(1) DEFAULT 0 NOT NULL,                    -- 수정
    CAN_APPROVE NUMBER(1) DEFAULT 0 NOT NULL,                    -- 결재(결재 가능 메뉴에서만 1)
    UPDATED_AT  VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT PK_USER_MENU_PERMS PRIMARY KEY (EMP_NO, MENU_KEY),
    CONSTRAINT FK_UMP_USER FOREIGN KEY (EMP_NO) REFERENCES USERS (EMP_NO)
);

CREATE TABLE ACCESS_LOG (
    LOG_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    OCCURRED_AT  VARCHAR2(40 CHAR)  NOT NULL,
    EMP_NO       VARCHAR2(7 CHAR),                               -- 모르면 NULL. FK 없음(없는 사번 시도도 남긴다)
    EMP_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,                   -- 1: 앞단 인증 주체, 0: 자기신고
    EVENT_TYPE   VARCHAR2(20 CHAR)  NOT NULL,                    -- LOGIN_OK / LOGIN_FAIL / LOGOUT / SCREEN_VIEW / API / DENIED
    HTTP_METHOD  VARCHAR2(10 CHAR),
    REQ_PATH     VARCHAR2(300 CHAR),                             -- 쿼리스트링 제외
    STATUS_CODE  NUMBER(3),
    CLIENT_IP    VARCHAR2(64 CHAR),
    USER_AGENT   VARCHAR2(200 CHAR),
    DURATION_MS  NUMBER(10),
    DETAIL       VARCHAR2(300 CHAR),                             -- 요약만. 본문·비밀번호·개인정보 금지
    CONSTRAINT PK_ACCESS_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_ACCESS_LOG_AT  ON ACCESS_LOG (OCCURRED_AT);
CREATE INDEX IDX_ACCESS_LOG_EMP ON ACCESS_LOG (EMP_NO, OCCURRED_AT);

CREATE TABLE PERM_CHANGE_LOG (
    CHG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CHANGED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),                             -- 바꾼 사람(자기신고일 수 있다)
    TARGET_EMP_NO  VARCHAR2(7 CHAR)   NOT NULL,                  -- 바뀐 사람
    ITEM           VARCHAR2(100 CHAR) NOT NULL,                  -- 예: perm:approvals:CAN_VIEW, user:STATUS
    BEFORE_VALUE   VARCHAR2(200 CHAR),
    AFTER_VALUE    VARCHAR2(200 CHAR),
    CONSTRAINT PK_PERM_CHANGE_LOG PRIMARY KEY (CHG_ID)
);
CREATE INDEX IDX_PERM_CHG_TARGET ON PERM_CHANGE_LOG (TARGET_EMP_NO, CHANGED_AT);
