-- kgi-ggreport-web — Oracle 정본 (047) : 이사회 회의록 BOARD_MINUTES 및 _UTTER/_SEG/_ITEM/_SCOPE/_REV/_LOG/_ACT
-- 외래키·CHECK·UNIQUE 없음(PK·조회 인덱스만). 참조는 서비스가 저장 전에 확인:
--   MATERIAL_ID -> BOARD_MATERIAL(BID_CASE_ID·INSTITUTION_ID·BOARD_YEAR 는 그 자료의 사본), *_BY·*_EMP_NO·SCOPE.GRANT_VALUE(EMP) -> USERS
-- ⚠️ 원본 파일·파일명·추가 가림 단어는 어디에도 저장하지 않는다. BODY·*_TEXT·TITLE·KEYWORDS 는 가린 뒤의 글만.
-- ⚠️ 참석자 N 과 사번·이름을 잇는 칸을 두지 않는다(security R14).
-- ⚠️ _LOG·_ACT 는 추가 전용 — 앱 계정에 UPDATE/DELETE 미부여 권장(NEXT 27 원칙). _UTTER·_SEG·_ITEM·_SCOPE·_REV 는 삭제 때 지운다(본문 소거).
-- ⚠️ ACT.SCREEN_ID·BUTTON_ID·ACTOR_EMP_NO 는 자기신고 값이다(EMP_VERIFIED=1 일 때만 앞단 인증 주체).
-- ⚠️ 멱등하지 않다. 020 적용 뒤 한 번만.
-- Oracle 12c 이상 전제(IDENTITY) — 부모 020·024·026·034 와 같다. 037 이후 '11g 호환' 표기는 새 독립 표의 권장이며 020 하위인 이 파일은 예외다.
-- DBA 권한 메모: _SCOPE 는 SELECT·INSERT·DELETE·UPDATE(GRANT_UNTIL,GRANTED_BY,GRANTED_AT), _UTTER·_ITEM 은 UPDATE(BODY,EDITED_YN,DONE_*) 포함, _LOG·_ACT 는 SELECT·INSERT 만.
-- 되돌리기(데이터 소멸, 운영 금지): DROP TABLE BOARD_MINUTES_ACT; DROP TABLE BOARD_MINUTES_LOG; DROP TABLE BOARD_MINUTES_REV;
--   DROP TABLE BOARD_MINUTES_SCOPE; DROP TABLE BOARD_MINUTES_ITEM; DROP TABLE BOARD_MINUTES_SEG; DROP TABLE BOARD_MINUTES_UTTER; DROP TABLE BOARD_MINUTES;
--------------------------------------------------------------------------------
CREATE TABLE BOARD_MINUTES (
    MINUTES_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    MATERIAL_ID     NUMBER             NOT NULL,
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    INSTITUTION_ID  VARCHAR2(64 CHAR)  NOT NULL,
    BOARD_YEAR      NUMBER(4)          NOT NULL,
    MEETING_DATE    VARCHAR2(10 CHAR)  NOT NULL,                 -- yyyy-MM-dd
    TITLE           VARCHAR2(100 CHAR) NOT NULL,                 -- 가린 뒤
    ENC_TRANSCRIPT  VARCHAR2(10 CHAR)  NOT NULL,                 -- UTF-8 / CP949
    ENC_TIMELINE    VARCHAR2(10 CHAR),
    ENC_SUMMARY     VARCHAR2(10 CHAR),
    UTTER_CNT       NUMBER(6)  DEFAULT 0 NOT NULL,
    SPEAKER_CNT     NUMBER(4)  DEFAULT 0 NOT NULL,
    DURATION_SEC    NUMBER(7)  DEFAULT 0 NOT NULL,               -- 마지막 발언 시작 시각
    NOISE_CNT       NUMBER(6)  DEFAULT 0 NOT NULL,
    SEG_CNT         NUMBER(4)  DEFAULT 0 NOT NULL,
    MASK_PII_CNT    NUMBER(6)  DEFAULT 0 NOT NULL,               -- 건수만, 값 없음
    MASK_NAME_CNT   NUMBER(6)  DEFAULT 0 NOT NULL,
    MASK_TITLE_CNT  NUMBER(6)  DEFAULT 0 NOT NULL,               -- 성+직함
    MASK_TERM_CNT   NUMBER(6)  DEFAULT 0 NOT NULL,               -- 담당자 지정
    MASK_LINE_CNT   NUMBER(6)  DEFAULT 0 NOT NULL,               -- 안전망이 줄 통째로 가림
    MASK_LABEL_CNT  NUMBER(4)  DEFAULT 0 NOT NULL,               -- 이름으로 바뀐 화자 머리 → 참석자 k
    RELEASE_CNT     NUMBER(4)  DEFAULT 0 NOT NULL,               -- 이름 사전 오탐 해제 건수
    RULE_VER        VARCHAR2(20 CHAR)  NOT NULL,                 -- 파서·가림 규칙 버전(예 'm1')
    CONTENT_DIGEST  VARCHAR2(64 CHAR)  NOT NULL,                 -- 가린 결과 SHA-256(중복 등록 409)
    REV_NO          NUMBER(9)  DEFAULT 0 NOT NULL,               -- 낙관적 락
    DELETED_YN      NUMBER(1)  DEFAULT 0 NOT NULL,
    DELETED_BY      VARCHAR2(7 CHAR),
    DELETED_AT      VARCHAR2(40 CHAR),
    CREATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    UPDATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    UPDATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MINUTES PRIMARY KEY (MINUTES_ID)
);
CREATE INDEX IDX_BMN_MAT  ON BOARD_MINUTES (MATERIAL_ID);
CREATE INDEX IDX_BMN_DATE ON BOARD_MINUTES (DELETED_YN, MEETING_DATE);
CREATE INDEX IDX_BMN_BY   ON BOARD_MINUTES (CREATED_BY);

CREATE TABLE BOARD_MINUTES_UTTER (
    MINUTES_ID  NUMBER     NOT NULL,
    SEQ_NO      NUMBER(6)  NOT NULL,
    SPEAKER_NO  NUMBER(3)  NOT NULL,                             -- 참석자 N 의 N 만
    START_SEC   NUMBER(7)  NOT NULL,
    NOISE_YN    NUMBER(1)  DEFAULT 0 NOT NULL,
    EDITED_YN   NUMBER(1)  DEFAULT 0 NOT NULL,
    BODY        CLOB       NOT NULL,                             -- 정렬·DISTINCT 금지
    CONSTRAINT PK_BOARD_MINUTES_UTTER PRIMARY KEY (MINUTES_ID, SEQ_NO)
);

CREATE TABLE BOARD_MINUTES_SEG (
    MINUTES_ID  NUMBER     NOT NULL,
    SEG_NO      NUMBER(4)  NOT NULL,
    START_SEC   NUMBER(7)  NOT NULL,
    END_SEC     NUMBER(7)  NOT NULL,
    KEYWORDS    VARCHAR2(500 CHAR),                              -- 쉼표 구분 원형(가린 뒤)
    CONSTRAINT PK_BOARD_MINUTES_SEG PRIMARY KEY (MINUTES_ID, SEG_NO)
);

CREATE TABLE BOARD_MINUTES_ITEM (
    MINUTES_ID     NUMBER             NOT NULL,
    ITEM_NO        NUMBER(5)          NOT NULL,
    KIND_CD        VARCHAR2(10 CHAR)  NOT NULL,                  -- SEG / TOPIC / TODO / OTHER
    SEG_NO         NUMBER(4),                                    -- KIND_CD=SEG 일 때
    SECTION_NO     NUMBER(3),                                    -- OTHER 묶음 번호
    SECTION_TITLE  VARCHAR2(100 CHAR),                           -- OTHER 제목(가린 뒤)
    SORT_NO        NUMBER(5)          NOT NULL,
    BODY           VARCHAR2(1000 CHAR) NOT NULL,
    EDITED_YN      NUMBER(1) DEFAULT 0 NOT NULL,
    DONE_YN        NUMBER(1) DEFAULT 0 NOT NULL,                 -- TODO 만
    DONE_BY        VARCHAR2(7 CHAR),
    DONE_AT        VARCHAR2(40 CHAR),
    CONSTRAINT PK_BOARD_MINUTES_ITEM PRIMARY KEY (MINUTES_ID, ITEM_NO)
);

CREATE TABLE BOARD_MINUTES_SCOPE (
    MINUTES_ID   NUMBER             NOT NULL,
    GRANT_TYPE   VARCHAR2(10 CHAR)  NOT NULL,                    -- EMP (ROLE 은 자리만, 1차 미사용)
    GRANT_VALUE  VARCHAR2(30 CHAR)  NOT NULL,                    -- 사번
    GRANT_UNTIL  VARCHAR2(10 CHAR)  NOT NULL,                    -- yyyy-MM-dd, 그날까지 열람
    GRANTED_BY   VARCHAR2(7 CHAR)   NOT NULL,
    GRANTED_AT   VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MINUTES_SCOPE PRIMARY KEY (MINUTES_ID, GRANT_TYPE, GRANT_VALUE)
);
CREATE INDEX IDX_BMNS_VAL ON BOARD_MINUTES_SCOPE (GRANT_TYPE, GRANT_VALUE);

-- ⚠️ REV 의 OLD_TEXT/NEW_TEXT 에는 저장 때 현재 가림 규칙으로 다시 가린 글만 넣는다(MinutesMasker.requireClean 이 돌려준 정규화 글).
--    이력 열람은 H(부장급)·등록자만 — 4단계 서비스가 지킨다(DDL 은 열을 제한하지 못한다).
CREATE TABLE BOARD_MINUTES_REV (
    MINUTES_ID   NUMBER             NOT NULL,
    REV_NO       NUMBER(9)          NOT NULL,
    TARGET_KIND  VARCHAR2(10 CHAR)  NOT NULL,                    -- UTTER / ITEM / META
    TARGET_NO    NUMBER(6),
    FIELD_CD     VARCHAR2(20 CHAR)  NOT NULL,                    -- BODY / TITLE / MEETING_DATE
    OLD_TEXT     CLOB,
    NEW_TEXT     CLOB,
    EDITED_BY    VARCHAR2(7 CHAR)   NOT NULL,
    EDITED_AT    VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MINUTES_REV PRIMARY KEY (MINUTES_ID, REV_NO)
);

CREATE TABLE BOARD_MINUTES_LOG (
    LOG_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    MINUTES_ID    NUMBER             NOT NULL,
    MATERIAL_ID   NUMBER             NOT NULL,
    EVENT_CD      VARCHAR2(20 CHAR)  NOT NULL,                   -- UPLOAD/EDIT/TODO_DONE/TODO_UNDONE/SCOPE_ADD/SCOPE_EXTEND/SCOPE_REMOVE/DELETE
    REV_NO        NUMBER(9),
    TARGET_KIND   VARCHAR2(10 CHAR),
    TARGET_NO     NUMBER(6),
    SCOPE_BEFORE  VARCHAR2(400 CHAR),                            -- 사번 목록(쉼표)만 — R18
    SCOPE_AFTER   VARCHAR2(400 CHAR),
    ACTOR_EMP_NO  VARCHAR2(7 CHAR)   NOT NULL,
    EMP_VERIFIED  NUMBER(1) DEFAULT 0 NOT NULL,
    LOGGED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MINUTES_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_BMNL_MIN ON BOARD_MINUTES_LOG (MINUTES_ID, LOG_ID);

CREATE TABLE BOARD_MINUTES_ACT (
    ACT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    MINUTES_ID    NUMBER,                                        -- 미리보기·업로드 실패는 NULL
    MATERIAL_ID   NUMBER,
    ACTION_CD     VARCHAR2(20 CHAR)  NOT NULL,
    OUTCOME       VARCHAR2(10 CHAR)  NOT NULL,                   -- OK/DENIED/HIDDEN/BLOCKED/INVALID/ERROR
    VIA_CD        VARCHAR2(10 CHAR)  NOT NULL,                   -- DEFAULT/HEAD/UPLOADER/GRANTEE/WRITER/ADMIN/NONE
    ACTOR_EMP_NO  VARCHAR2(7 CHAR),
    EMP_VERIFIED  NUMBER(1) DEFAULT 0 NOT NULL,
    SCREEN_ID     VARCHAR2(30 CHAR)  NOT NULL,
    BUTTON_ID     VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID      NUMBER(1) DEFAULT 0 NOT NULL,
    LOGGED_AT     VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MINUTES_ACT PRIMARY KEY (ACT_ID)
);
CREATE INDEX IDX_BMNA_MIN   ON BOARD_MINUTES_ACT (MINUTES_ID, ACT_ID);
CREATE INDEX IDX_BMNA_ACTOR ON BOARD_MINUTES_ACT (ACTOR_EMP_NO, ACT_ID);
