CREATE TABLE BOARD_MATERIAL (
    MATERIAL_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    INSTITUTION_ID  VARCHAR2(64 CHAR)  NOT NULL,                 -- 검색용 사본. 만들 때 BID_CASES 에서 복사
    BOARD_YEAR      NUMBER(4)          NOT NULL,                 -- 화면 '연도'
    STATUS_CD       VARCHAR2(20 CHAR)  DEFAULT 'PREP' NOT NULL,  -- COMMON_CODE BOARD_STATUS: PREP/DRAFT/SUBMITTED/CONFIRMED
    RESULT_CD       VARCHAR2(20 CHAR),                           -- COMMON_CODE BOARD_RESULT: SCHEDULED/PASSED/REJECTED. 확정 뒤에만 값이 생긴다
    MEETING_DATE    VARCHAR2(10 CHAR),                           -- 개최일 yyyy-MM-dd. 의결 예정이면 필수
    SUBMIT_REQ_ID   NUMBER,                                      -- 결재 중인 BOARD_SUBMIT 요청(SUBMITTED 일 때만)
    SUBMIT_SNAP     NUMBER(6),                                   -- 제출한 버전 번호
    CONFIRMED_SNAP  NUMBER(6),                                   -- 확정된 버전 번호
    CONFIRMED_BY    VARCHAR2(7 CHAR),                            -- 최종 승인자 사번
    CONFIRMED_AT    VARCHAR2(40 CHAR),
    FORM_ID         VARCHAR2(50 CHAR)  NOT NULL,                 -- 만들 때 고정하는 양식('default_doc' 또는 BOARD_FORM.FORM_ID 문자열)
    FORM_VER        NUMBER(6)          DEFAULT 0 NOT NULL,       -- default_doc 이면 0
    CUR_SNAP        NUMBER(6)          DEFAULT 0 NOT NULL,       -- 최신 버전 번호(0 = 저장본 없음). 낙관적 락 겸용
    LAST_SAVED_BY   VARCHAR2(7 CHAR),
    LAST_SAVED_AT   VARCHAR2(40 CHAR),
    CREATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    CREATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    UPDATED_BY      VARCHAR2(7 CHAR)   NOT NULL,
    UPDATED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MATERIAL PRIMARY KEY (MATERIAL_ID)
);
CREATE INDEX IDX_BM_CASE   ON BOARD_MATERIAL (BID_CASE_ID);
CREATE INDEX IDX_BM_INST   ON BOARD_MATERIAL (INSTITUTION_ID, BOARD_YEAR);
CREATE INDEX IDX_BM_STATUS ON BOARD_MATERIAL (STATUS_CD, MEETING_DATE);

CREATE TABLE BOARD_MATERIAL_SNAP (
    MATERIAL_ID     NUMBER             NOT NULL,
    SNAP_NO         NUMBER(6)          NOT NULL,                 -- 1부터. 자료 안에서 증가
    VALUES_JSON     CLOB               NOT NULL,                 -- {"v":1,"tables":{"<표ref>":{"<칸키>":"값"}}} — 값이 있는 칸만. 정렬·DISTINCT 금지
    NOTE            VARCHAR2(200 CHAR),                          -- 비면 NULL(Oracle 은 빈 문자열을 NULL 로 본다). 앱이 정규화
    SAVED_BY        VARCHAR2(7 CHAR)   NOT NULL,
    SAVED_AT        VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MATERIAL_SNAP PRIMARY KEY (MATERIAL_ID, SNAP_NO)
);

CREATE TABLE BOARD_MATERIAL_LOG (
    LOG_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    MATERIAL_ID     NUMBER             NOT NULL,
    EVENT_CD        VARCHAR2(20 CHAR)  NOT NULL,                 -- CREATE / SUBMIT / WITHDRAW / CONFIRM / REJECT / REWORK / RESULT / HANDOVER
    FROM_STATUS     VARCHAR2(20 CHAR),
    TO_STATUS       VARCHAR2(20 CHAR),
    FROM_RESULT     VARCHAR2(20 CHAR),
    TO_RESULT       VARCHAR2(20 CHAR),
    MEETING_DATE    VARCHAR2(10 CHAR),
    FROM_EMP_NO     VARCHAR2(7 CHAR),                            -- HANDOVER: 해제된 담당자
    TO_EMP_NO       VARCHAR2(7 CHAR),                            -- HANDOVER: 인계 받은(추가된) 담당자
    REQ_ID          NUMBER,                                      -- SUBMIT/WITHDRAW/CONFIRM/REJECT/HANDOVER: 결재 요청 번호
    REASON          VARCHAR2(200 CHAR),                          -- REWORK 사유(서버가 검사한 자유 글)
    ACTOR_EMP_NO    VARCHAR2(7 CHAR)   NOT NULL,
    EMP_VERIFIED    NUMBER(1)          DEFAULT 0 NOT NULL,       -- 1 = 앞단 인증 주체, 0 = X-Emp-No 자기신고(위조 가능)
    LOGGED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_BOARD_MATERIAL_LOG PRIMARY KEY (LOG_ID)
);
CREATE INDEX IDX_BML_MAT ON BOARD_MATERIAL_LOG (MATERIAL_ID, LOG_ID);
CREATE INDEX IDX_BML_REQ ON BOARD_MATERIAL_LOG (REQ_ID);

CREATE TABLE BOARD_MATERIAL_ACT (
    ACT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    MATERIAL_ID     NUMBER             NOT NULL,                 -- 어느 자료
    BID_CASE_ID     VARCHAR2(64 CHAR)  NOT NULL,
    ACTION_CD       VARCHAR2(20 CHAR)  NOT NULL,                 -- VIEW / SNAPSHOT_LIST / SNAPSHOT_VIEW / HISTORY / REVIEW / ACTS / SAVE / SUBMIT / WITHDRAW / REWORK / RESULT
    OUTCOME         VARCHAR2(20 CHAR)  NOT NULL,                 -- OK / DENIED(403) / HIDDEN(404) / BLOCKED(409) / INVALID(400·422) / ERROR
    STATUS_CD       VARCHAR2(20 CHAR)  NOT NULL,                 -- 행위 직전의 자료 상태(항상 CONFIRMED — 확정 건만 기록)
    RESULT_CD       VARCHAR2(20 CHAR),                           -- 행위 직전의 결과
    SNAP_NO         NUMBER(6),                                   -- 확정 버전 번호
    ACTOR_EMP_NO    VARCHAR2(7 CHAR),                            -- 누가(사번 없는 호출이면 NULL)
    EMP_VERIFIED    NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID       VARCHAR2(30 CHAR)  NOT NULL,                 -- 어느 화면(허용 목록, 아니면 UNKNOWN)
    BUTTON_ID       VARCHAR2(30 CHAR)  NOT NULL,                 -- 어느 버튼(허용 목록, 아니면 UNKNOWN)
    UI_VALID        NUMBER(1)          DEFAULT 0 NOT NULL,       -- 1 = 두 값이 모두 허용 목록 안
    LOGGED_AT       VARCHAR2(40 CHAR)  NOT NULL,                 -- 언제
    CONSTRAINT PK_BOARD_MATERIAL_ACT PRIMARY KEY (ACT_ID)
);
CREATE INDEX IDX_BMA_MAT ON BOARD_MATERIAL_ACT (MATERIAL_ID, ACT_ID);
CREATE INDEX IDX_BMA_ACTOR ON BOARD_MATERIAL_ACT (ACTOR_EMP_NO, ACT_ID);

