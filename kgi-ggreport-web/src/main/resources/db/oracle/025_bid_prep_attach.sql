-- ⚠️ PII_NOTE 에는 종류·건수만 넣는다("이메일 2, 휴대폰 1"). 값 원문 금지. 주민·외국인등록·카드번호가 나오면 저장 자체를 거부하므로 이 칸에는 이메일·전화만 온다.
-- ⚠️ UPLOADED_VERIFIED=0 이면 올린 사람 사번은 자기신고(X-Emp-No)다 — '검증됨'으로 표시하지 않는다.
-- ⚠️ 멱등하지 않다. 024 이후 한 번만 돌린다. 디스크 폴더(ggreport.prep-attach-dir)는 백업 대상에 넣어야 한다 — DB 와 파일이 함께 정본이다.
-- 되돌리기(데이터 소멸, 운영 금지): DROP TABLE BID_PREP_ATTACH; DELETE FROM COMMON_CODE WHERE CODE_GROUP = 'PREP_PII';
