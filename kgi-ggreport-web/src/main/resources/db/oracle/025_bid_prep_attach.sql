CREATE TABLE BID_PREP_ATTACH (
    ATTACH_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BID_CASE_ID       VARCHAR2(64 CHAR)  NOT NULL,
    TASK_CD           VARCHAR2(20 CHAR)  NOT NULL,        -- T3(수익성 분석표 확정본 후보) / T4(RFP 붙임서류)
    ORIG_NAME         VARCHAR2(200 CHAR) NOT NULL,
    EXT_CD            VARCHAR2(10 CHAR)  NOT NULL,        -- xlsx / docx / pdf / hwpx (허용 목록은 서버 코드)
    SIZE_BYTES        NUMBER(12)         NOT NULL,
    SHA256            VARCHAR2(64 CHAR)  NOT NULL,
    STORE_KEY         VARCHAR2(40 CHAR)  NOT NULL,        -- 서버가 만든 32자리 16진수. 덮어쓰기 없음
    PII_STATE         VARCHAR2(20 CHAR)  NOT NULL,        -- PREP_PII: CHECKED / UNCHECKED(검사 못 함: 스캔 PDF 등)
    PII_NOTE          VARCHAR2(100 CHAR),                 -- 종류·건수만. 비면 NULL
    VALID_YN          NUMBER(1)          DEFAULT 1 NOT NULL,
    UPLOADED_BY       VARCHAR2(7 CHAR)   NOT NULL,
    UPLOADED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    UPLOADED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    VOIDED_BY         VARCHAR2(7 CHAR),
    VOIDED_AT         VARCHAR2(40 CHAR),
    CONSTRAINT PK_BID_PREP_ATTACH PRIMARY KEY (ATTACH_ID)
);
CREATE INDEX IDX_BPAT_CASE ON BID_PREP_ATTACH (BID_CASE_ID, TASK_CD, ATTACH_ID);

