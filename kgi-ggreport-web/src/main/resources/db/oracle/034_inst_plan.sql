CREATE TABLE INST_PLAN_IMPORT (                      -- 반입 1건 = 판 1개
    IMPORT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID    VARCHAR2(64 CHAR)  NOT NULL,
    ORIGIN_CD         VARCHAR2(20 CHAR)  NOT NULL,      -- PLAN_ORIGIN(IMPORT / SEED_TXT) — 서버가 경로로 정한다
    FILE_DATE         VARCHAR2(10 CHAR)  NOT NULL,      -- 파일 이름의 날짜 = 문서 확인일 중 가장 늦은 날
    FILE_SHA256       VARCHAR2(64 CHAR)  NOT NULL,      -- 올라온 원본 바이트 해시(원래 파일 이름은 저장하지 않는다)
    FILE_BYTES        NUMBER(12)         NOT NULL,
    ITEM_COUNT        NUMBER(6)          NOT NULL,      -- 사업 행 수
    DOC_COUNT         NUMBER(4)          NOT NULL,
    WARN_COUNT        NUMBER(6)          DEFAULT 0 NOT NULL,
    BATCH_ID          VARCHAR2(64 CHAR),                -- 수집 배치 id(있으면)
    IMPORTED_BY       VARCHAR2(7 CHAR)   NOT NULL,
    IMPORTED_AT       VARCHAR2(40 CHAR)  NOT NULL,
    IMPORTED_VERIFIED NUMBER(1)          DEFAULT 0 NOT NULL,
    CONSTRAINT PK_INST_PLAN_IMPORT PRIMARY KEY (IMPORT_ID)
);
CREATE INDEX IDX_IPI_INST ON INST_PLAN_IMPORT (INSTITUTION_ID, IMPORT_ID);

CREATE TABLE INST_PLAN_DOC (                         -- 계획 문서 한 권(판 안)
    DOC_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    IMPORT_ID       NUMBER             NOT NULL,
    INSTITUTION_ID  VARCHAR2(64 CHAR)  NOT NULL,
    DOC_SEQ         NUMBER(4)          NOT NULL,        -- 파일 안 순서
    TITLE           VARCHAR2(200 CHAR) NOT NULL,
    SRC_KIND_CD     VARCHAR2(20 CHAR)  NOT NULL,        -- PLAN_SRC_KIND
    PERIOD_FROM     NUMBER(4)          NOT NULL,
    PERIOD_TO       NUMBER(4)          NOT NULL,        -- '기간 지남' = PERIOD_TO < 올해(조회 시 계산, 저장 안 함)
    SRC_URL         VARCHAR2(1000 CHAR),                -- http/https, 계정정보 금지, 500자 검사
    URL_MISSING     NUMBER(1)          DEFAULT 0 NOT NULL,
    CHECKED_ON      VARCHAR2(10 CHAR)  NOT NULL,        -- 확인일('오래됨' = 12개월 초과, 조회 시 계산)
    COLLECTOR_AGENT VARCHAR2(60 CHAR)  NOT NULL,        -- 수집 프로그램 식별자(예 plan-collector/1.0, 시드는 서버 고정 seed-txt-convert/1). 사람 정보 없음. 누가 올렸나 = INST_PLAN_IMPORT.IMPORTED_BY
    PAGE_RANGE      VARCHAR2(20 CHAR),
    NOTE            VARCHAR2(500 CHAR),
    CONSTRAINT PK_INST_PLAN_DOC PRIMARY KEY (DOC_ID)
);
CREATE INDEX IDX_IPD_IMPORT ON INST_PLAN_DOC (IMPORT_ID, DOC_SEQ);

CREATE TABLE INST_PLAN_ITEM (                        -- 사업·하위사업 1개 = 1행
    ITEM_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DOC_ID           NUMBER             NOT NULL,
    IMPORT_ID        NUMBER             NOT NULL,
    INSTITUTION_ID   VARCHAR2(64 CHAR)  NOT NULL,
    ROW_NO           NUMBER(6)          NOT NULL,       -- 파일 행 번호(머리행 다음 = 1)
    FIELD_NO         VARCHAR2(20 CHAR),                 -- 분야(장) 번호 원문
    FIELD_NAME       VARCHAR2(100 CHAR),
    ITEM_NO          VARCHAR2(50 CHAR)  NOT NULL,       -- 사업번호 원문("5-1", "6-1(52번)")
    PARENT_NO        VARCHAR2(50 CHAR),                 -- 상위사업번호(2단까지)
    ITEM_NAME        VARCHAR2(300 CHAR) NOT NULL,
    CONTENT          VARCHAR2(1000 CHAR),
    BUDGET_STATE_CD  VARCHAR2(20 CHAR)  NOT NULL,       -- PLAN_BUDGET_STATE
    BUDGET_AMOUNT    NUMBER(18,3),                      -- AMOUNT 일 때만, 0 초과
    BUDGET_UNIT_CD   VARCHAR2(20 CHAR),                 -- PLAN_BUDGET_UNIT(원문 단위)
    BUDGET_YEARS     VARCHAR2(300 CHAR),                -- 연차 원문 '2024:600;2025:600;장기:200'(있는 해만)
    PAGE_NO          VARCHAR2(20 CHAR),
    CHECK_CD         VARCHAR2(20 CHAR)  NOT NULL,       -- PLAN_CHECK(빈칸이면 NOT_CHECKED)
    PROGRESS_CD      VARCHAR2(20 CHAR),                 -- PLAN_PROGRESS(공약이행 문서만)
    EXEC_RATE        NUMBER(4,1),                       -- 이행률 %(공약이행 문서만)
    NOTE             VARCHAR2(500 CHAR),
    CONSTRAINT PK_INST_PLAN_ITEM PRIMARY KEY (ITEM_ID)
);
CREATE INDEX IDX_IPT_DOC ON INST_PLAN_ITEM (DOC_ID, ROW_NO);
CREATE INDEX IDX_IPT_IMPORT ON INST_PLAN_ITEM (IMPORT_ID);

CREATE TABLE INST_PLAN_ACT (                         -- 반입·내려받기 감사(추가 전용, INST_HEAD_ACT 와 같은 모양)
    ACT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    INSTITUTION_ID VARCHAR2(64 CHAR)  NOT NULL,         -- 형식 밖·여러 기관이면 'NONE'
    IMPORT_ID      NUMBER,
    ACTION_CD      VARCHAR2(30 CHAR)  NOT NULL,         -- PLAN_ACTION
    OUTCOME        VARCHAR2(20 CHAR)  NOT NULL,         -- OK / DENIED / HIDDEN / BLOCKED / INVALID / ERROR
    ITEM_COUNT     NUMBER(6),
    FILE_SHA256    VARCHAR2(64 CHAR),                   -- 실패한 반입도 해시는 남긴다(내용·파일 이름은 남기지 않는다)
    ACTOR_EMP_NO   VARCHAR2(7 CHAR),
    EMP_VERIFIED   NUMBER(1)          DEFAULT 0 NOT NULL,
    SCREEN_ID      VARCHAR2(30 CHAR)  NOT NULL,         -- 서버 고정값(PlanUiIds) — 헤더로 받지 않는다
    BUTTON_ID      VARCHAR2(30 CHAR)  NOT NULL,
    UI_VALID       NUMBER(1)          DEFAULT 0 NOT NULL,
    LOGGED_AT      VARCHAR2(40 CHAR)  NOT NULL,
    CONSTRAINT PK_INST_PLAN_ACT PRIMARY KEY (ACT_ID)
);
CREATE INDEX IDX_IPA_INST ON INST_PLAN_ACT (INSTITUTION_ID, ACT_ID);
CREATE INDEX IDX_IPA_ACTOR ON INST_PLAN_ACT (ACTOR_EMP_NO, LOGGED_AT);

