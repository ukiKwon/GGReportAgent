-- 외래키·CHECK·UNIQUE 없음(PK 와 조회용 인덱스만). 참조는 서비스가 확인한다:
--   INSTITUTION_ID -> INSTITUTIONS, IMPORT_ID -> INST_PLAN_IMPORT, DOC_ID -> INST_PLAN_DOC, *_CD -> COMMON_CODE, *_BY·ACTOR_EMP_NO -> USERS.
-- 판 규칙: 반입 1건 = IMPORT 1행 + 그 파일의 문서·사업 전부. 고치지 않고 새 판을 INSERT 한다(UPDATE·DELETE 없음).
--   기관의 현재 자료 = 그 기관의 가장 큰 IMPORT_ID 판.
-- 예산: 원문 숫자(BUDGET_AMOUNT, 0 금지)와 원문 단위(BUDGET_UNIT_CD)를 함께 둔다. 원문의 '-'·빈칸은 BUDGET_STATE_CD 로만 적는다.
-- URL_MISSING=1 은 ORIGIN_CD='SEED_TXT'(서버 고정 시드 경로)에서만 생긴다. 바깥 반입은 출처 URL 필수.
-- 서버는 SRC_URL 을 열지 않는다(화면 링크 표시용 문자열).
-- ⚠️ 사번은 자기신고(X-Emp-No)일 수 있다. *_VERIFIED·EMP_VERIFIED=0 이면 '검증됨'으로 표시하지 않는다.
-- ⚠️ DB 권한(DBA): 앱 계정은 네 표 모두 SELECT·INSERT 만(UPDATE·DELETE 없음).
-- ⚠️ 멱등하지 않다. 016(COMMON_CODE) 이후 한 번만 돌린다.
-- 되돌리기(데이터 소멸, 운영 금지): DROP TABLE INST_PLAN_ACT; DROP TABLE INST_PLAN_ITEM; DROP TABLE INST_PLAN_DOC; DROP TABLE INST_PLAN_IMPORT;
