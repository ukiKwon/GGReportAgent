CREATE TABLE INST_HEAD (
    HEAD_ID          BIGINT        NOT NULL AUTO_INCREMENT,
    INSTITUTION_ID   VARCHAR(64),
    SRC_ORG_CD       VARCHAR(20),
    SRC_ORG_NAME     VARCHAR(100),
    STATUS_CD        VARCHAR(20)   NOT NULL,
    ORIGIN_CD        VARCHAR(20)   NOT NULL,
    BATCH_ID         VARCHAR(64),
    CREATED_BY       VARCHAR(7)    NOT NULL,
    CREATED_AT       VARCHAR(40)   NOT NULL,
    CREATED_VERIFIED SMALLINT      NOT NULL DEFAULT 0,
    DECIDED_BY       VARCHAR(7),
    DECIDED_AT       VARCHAR(40),
    ENDED_BY         VARCHAR(7),
    ENDED_AT         VARCHAR(40),
    MATCHED_BY       VARCHAR(7),
    MATCHED_AT       VARCHAR(40),
    MERGED_INTO_ID   BIGINT,
    PRIMARY KEY (HEAD_ID),
    KEY IDX_IH_INST (INSTITUTION_ID, STATUS_CD),
    KEY IDX_IH_STATUS (STATUS_CD, HEAD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_HEAD_ITEM (
    ITEM_ID          BIGINT        NOT NULL AUTO_INCREMENT,
    HEAD_ID          BIGINT        NOT NULL,
    INSTITUTION_ID   VARCHAR(64),
    FIELD_CD         VARCHAR(20)   NOT NULL,
    STATE_CD         VARCHAR(20)   NOT NULL,
    ORIGIN_CD        VARCHAR(20)   NOT NULL,
    BATCH_ID         VARCHAR(64),
    VAL_TEXT         VARCHAR(60),
    VAL_DATE         VARCHAR(10),
    VAL_FROM         VARCHAR(7),
    VAL_TO           VARCHAR(7),
    VAL_FLAG         SMALLINT,
    SRC_KIND_CD      VARCHAR(20)   NOT NULL,
    SRC_TITLE        VARCHAR(100)  NOT NULL,
    SRC_URL          VARCHAR(1000),
    SRC_PUBLISHED    VARCHAR(10),
    CHECKED_ON       VARCHAR(10)   NOT NULL,
    CREATED_BY       VARCHAR(7)    NOT NULL,
    CREATED_AT       VARCHAR(40)   NOT NULL,
    CREATED_VERIFIED SMALLINT      NOT NULL DEFAULT 0,
    DECIDED_BY       VARCHAR(7),
    DECIDED_AT       VARCHAR(40),
    SUPERSEDED_BY_ID BIGINT,
    VOIDED_BY        VARCHAR(7),
    VOIDED_AT        VARCHAR(40),
    PRIMARY KEY (ITEM_ID),
    KEY IDX_IHI_HEAD (HEAD_ID, FIELD_CD, STATE_CD),
    KEY IDX_IHI_INST (INSTITUTION_ID, STATE_CD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_HEAD_PHOTO (
    PHOTO_ID          BIGINT        NOT NULL AUTO_INCREMENT,
    HEAD_ID           BIGINT        NOT NULL,
    INSTITUTION_ID    VARCHAR(64)   NOT NULL,
    STATE_CD          VARCHAR(20)   NOT NULL,
    STORE_KEY         VARCHAR(40)   NOT NULL,
    SHA256            VARCHAR(64)   NOT NULL,
    ORIG_SHA256       VARCHAR(64)   NOT NULL,
    ORIG_EXT          VARCHAR(10)   NOT NULL,
    SIZE_BYTES        BIGINT        NOT NULL,
    IMG_W             INT           NOT NULL,
    IMG_H             INT           NOT NULL,
    LICENSE_CD        VARCHAR(20)   NOT NULL,
    SRC_KIND_CD       VARCHAR(20)   NOT NULL,
    SRC_TITLE         VARCHAR(100)  NOT NULL,
    SRC_URL           VARCHAR(1000),
    CHECKED_ON        VARCHAR(10)   NOT NULL,
    UPLOADED_BY       VARCHAR(7)    NOT NULL,
    UPLOADED_AT       VARCHAR(40)   NOT NULL,
    UPLOADED_VERIFIED SMALLINT      NOT NULL DEFAULT 0,
    ENDED_BY          VARCHAR(7),
    ENDED_AT          VARCHAR(40),
    PRIMARY KEY (PHOTO_ID),
    KEY IDX_IHP_HEAD (HEAD_ID, STATE_CD),
    KEY IDX_IHP_INST (INSTITUTION_ID, PHOTO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_HEAD_LOG (
    LOG_ID         BIGINT        NOT NULL AUTO_INCREMENT,
    INSTITUTION_ID VARCHAR(64),
    HEAD_ID        BIGINT,
    EVENT_CD       VARCHAR(30)   NOT NULL,
    ITEM_ID        BIGINT,
    FROM_ITEM_ID   BIGINT,
    PHOTO_ID       BIGINT,
    FROM_PHOTO_ID  BIGINT,
    FROM_HEAD_ID   BIGINT,
    BATCH_ID       VARCHAR(64),
    REASON         VARCHAR(200),
    ACTOR_EMP_NO   VARCHAR(7),
    ACTOR_ROLE     VARCHAR(20),
    SELF_FLAG      SMALLINT      NOT NULL DEFAULT 0,
    EMP_VERIFIED   SMALLINT      NOT NULL DEFAULT 0,
    LOGGED_AT      VARCHAR(40)   NOT NULL,
    PRIMARY KEY (LOG_ID),
    KEY IDX_IHL_INST (INSTITUTION_ID, LOG_ID),
    KEY IDX_IHL_EVENT (EVENT_CD, LOG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_HEAD_ACT (
    ACT_ID         BIGINT        NOT NULL AUTO_INCREMENT,
    INSTITUTION_ID VARCHAR(64)   NOT NULL,
    HEAD_ID        BIGINT,
    ACTION_CD      VARCHAR(30)   NOT NULL,
    OUTCOME        VARCHAR(20)   NOT NULL,
    TARGET_ID      BIGINT,
    ACTOR_EMP_NO   VARCHAR(7),
    EMP_VERIFIED   SMALLINT      NOT NULL DEFAULT 0,
    SCREEN_ID      VARCHAR(30)   NOT NULL,
    BUTTON_ID      VARCHAR(30)   NOT NULL,
    UI_VALID       SMALLINT      NOT NULL DEFAULT 0,
    LOGGED_AT      VARCHAR(40)   NOT NULL,
    PRIMARY KEY (ACT_ID),
    KEY IDX_IHA_INST (INSTITUTION_ID, ACT_ID),
    KEY IDX_IHA_ACTOR (ACTOR_EMP_NO, LOGGED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

