CREATE TABLE INST_BANK_CONTRACT (
    INSTITUTION_ID     VARCHAR(64)   NOT NULL,
    CONTRACT_NO        INT           NOT NULL,
    REV_NO             INT           NOT NULL,
    ACTION_CD          VARCHAR(10)   NOT NULL,
    ORIGIN_CD          VARCHAR(10)   NOT NULL,
    RANK_CD            VARCHAR(20)   NOT NULL,
    BANK_CD            VARCHAR(10)   NOT NULL,
    BANK_NAME_ETC      VARCHAR(30),
    TERM_FROM          VARCHAR(10),
    TERM_TO            VARCHAR(10)   NOT NULL,
    SRC_KIND           VARCHAR(20)   NOT NULL,
    SRC_URL            VARCHAR(500),
    SRC_NO             VARCHAR(50),
    CHECKED_DATE       VARCHAR(10)   NOT NULL,
    CHECKED_DEPT       VARCHAR(50),
    NOTE               VARCHAR(100),
    ACCOUNT_CD         VARCHAR(20),
    ACCOUNT_ETC        VARCHAR(30),
    OVERLAP_CONFIRMED  SMALLINT      NOT NULL DEFAULT 0,
    CANCEL_REASON_CD   VARCHAR(20),
    CANCEL_REASON_ETC  VARCHAR(50),
    EDITOR_EMP_NO      VARCHAR(7)    NOT NULL,
    EDITOR_NAME        VARCHAR(50)   NOT NULL,
    EMP_VERIFIED       SMALLINT      NOT NULL DEFAULT 0,
    SCREEN_ID          VARCHAR(30)   NOT NULL,
    BUTTON_ID          VARCHAR(30)   NOT NULL,
    UI_VALID           SMALLINT      NOT NULL DEFAULT 0,
    SAVED_AT           VARCHAR(40)   NOT NULL,
    PRIMARY KEY (INSTITUTION_ID, CONTRACT_NO, REV_NO),
    KEY IDX_IBC_EDITOR (EDITOR_EMP_NO, SAVED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

