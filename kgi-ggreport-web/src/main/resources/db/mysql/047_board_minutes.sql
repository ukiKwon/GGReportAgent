CREATE TABLE BOARD_MINUTES (
    MINUTES_ID      BIGINT       NOT NULL AUTO_INCREMENT,
    MATERIAL_ID     BIGINT       NOT NULL,
    BID_CASE_ID     VARCHAR(64)  NOT NULL,
    INSTITUTION_ID  VARCHAR(64)  NOT NULL,
    BOARD_YEAR      SMALLINT     NOT NULL,
    MEETING_DATE    VARCHAR(10)  NOT NULL,
    TITLE           VARCHAR(100) NOT NULL,
    ENC_TRANSCRIPT  VARCHAR(10)  NOT NULL,
    ENC_TIMELINE    VARCHAR(10),
    ENC_SUMMARY     VARCHAR(10),
    UTTER_CNT       INT          NOT NULL DEFAULT 0,
    SPEAKER_CNT     SMALLINT     NOT NULL DEFAULT 0,
    DURATION_SEC    INT          NOT NULL DEFAULT 0,
    NOISE_CNT       INT          NOT NULL DEFAULT 0,
    SEG_CNT         SMALLINT     NOT NULL DEFAULT 0,
    MASK_PII_CNT    INT          NOT NULL DEFAULT 0,
    MASK_NAME_CNT   INT          NOT NULL DEFAULT 0,
    MASK_TITLE_CNT  INT          NOT NULL DEFAULT 0,
    MASK_TERM_CNT   INT          NOT NULL DEFAULT 0,
    MASK_LINE_CNT   INT          NOT NULL DEFAULT 0,
    MASK_LABEL_CNT  SMALLINT     NOT NULL DEFAULT 0,
    RELEASE_CNT     SMALLINT     NOT NULL DEFAULT 0,
    RULE_VER        VARCHAR(20)  NOT NULL,
    CONTENT_DIGEST  VARCHAR(64)  NOT NULL,
    REV_NO          INT          NOT NULL DEFAULT 0,
    DELETED_YN      SMALLINT     NOT NULL DEFAULT 0,
    DELETED_BY      VARCHAR(7),
    DELETED_AT      VARCHAR(40),
    CREATED_BY      VARCHAR(7)   NOT NULL,
    CREATED_AT      VARCHAR(40)  NOT NULL,
    UPDATED_BY      VARCHAR(7)   NOT NULL,
    UPDATED_AT      VARCHAR(40)  NOT NULL,
    PRIMARY KEY (MINUTES_ID),
    KEY IDX_BMN_MAT (MATERIAL_ID),
    KEY IDX_BMN_DATE (DELETED_YN, MEETING_DATE),
    KEY IDX_BMN_BY (CREATED_BY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_UTTER (
    MINUTES_ID  BIGINT       NOT NULL,
    SEQ_NO      INT          NOT NULL,
    SPEAKER_NO  SMALLINT     NOT NULL,
    START_SEC   INT          NOT NULL,
    NOISE_YN    SMALLINT     NOT NULL DEFAULT 0,
    EDITED_YN   SMALLINT     NOT NULL DEFAULT 0,
    BODY        LONGTEXT     NOT NULL,
    PRIMARY KEY (MINUTES_ID, SEQ_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_SEG (
    MINUTES_ID  BIGINT       NOT NULL,
    SEG_NO      SMALLINT     NOT NULL,
    START_SEC   INT          NOT NULL,
    END_SEC     INT          NOT NULL,
    KEYWORDS    VARCHAR(500),
    PRIMARY KEY (MINUTES_ID, SEG_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_ITEM (
    MINUTES_ID     BIGINT        NOT NULL,
    ITEM_NO        INT           NOT NULL,
    KIND_CD        VARCHAR(10)   NOT NULL,
    SEG_NO         SMALLINT,
    SECTION_NO     SMALLINT,
    SECTION_TITLE  VARCHAR(100),
    SORT_NO        INT           NOT NULL,
    BODY           VARCHAR(1000) NOT NULL,
    EDITED_YN      SMALLINT      NOT NULL DEFAULT 0,
    DONE_YN        SMALLINT      NOT NULL DEFAULT 0,
    DONE_BY        VARCHAR(7),
    DONE_AT        VARCHAR(40),
    PRIMARY KEY (MINUTES_ID, ITEM_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_SCOPE (
    MINUTES_ID   BIGINT       NOT NULL,
    GRANT_TYPE   VARCHAR(10)  NOT NULL,
    GRANT_VALUE  VARCHAR(30)  NOT NULL,
    GRANT_UNTIL  VARCHAR(10)  NOT NULL,
    GRANTED_BY   VARCHAR(7)   NOT NULL,
    GRANTED_AT   VARCHAR(40)  NOT NULL,
    PRIMARY KEY (MINUTES_ID, GRANT_TYPE, GRANT_VALUE),
    KEY IDX_BMNS_VAL (GRANT_TYPE, GRANT_VALUE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ⚠️ REV 의 OLD_TEXT/NEW_TEXT 에는 저장 때 현재 가림 규칙으로 다시 가린 글만 넣는다(MinutesMasker.requireClean 이 돌려준 정규화 글).
--    이력 열람은 H(부장급)·등록자만 — 4단계 서비스가 지킨다(DDL 은 열을 제한하지 못한다).
CREATE TABLE BOARD_MINUTES_REV (
    MINUTES_ID   BIGINT       NOT NULL,
    REV_NO       INT          NOT NULL,
    TARGET_KIND  VARCHAR(10)  NOT NULL,
    TARGET_NO    INT,
    FIELD_CD     VARCHAR(20)  NOT NULL,
    OLD_TEXT     LONGTEXT,
    NEW_TEXT     LONGTEXT,
    EDITED_BY    VARCHAR(7)   NOT NULL,
    EDITED_AT    VARCHAR(40)  NOT NULL,
    PRIMARY KEY (MINUTES_ID, REV_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_LOG (
    LOG_ID        BIGINT       NOT NULL AUTO_INCREMENT,
    MINUTES_ID    BIGINT       NOT NULL,
    MATERIAL_ID   BIGINT       NOT NULL,
    EVENT_CD      VARCHAR(20)  NOT NULL,
    REV_NO        INT,
    TARGET_KIND   VARCHAR(10),
    TARGET_NO     INT,
    SCOPE_BEFORE  VARCHAR(400),
    SCOPE_AFTER   VARCHAR(400),
    ACTOR_EMP_NO  VARCHAR(7)   NOT NULL,
    EMP_VERIFIED  SMALLINT     NOT NULL DEFAULT 0,
    LOGGED_AT     VARCHAR(40)  NOT NULL,
    PRIMARY KEY (LOG_ID),
    KEY IDX_BMNL_MIN (MINUTES_ID, LOG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MINUTES_ACT (
    ACT_ID        BIGINT       NOT NULL AUTO_INCREMENT,
    MINUTES_ID    BIGINT,
    MATERIAL_ID   BIGINT,
    ACTION_CD     VARCHAR(20)  NOT NULL,
    OUTCOME       VARCHAR(10)  NOT NULL,
    VIA_CD        VARCHAR(10)  NOT NULL,
    ACTOR_EMP_NO  VARCHAR(7),
    EMP_VERIFIED  SMALLINT     NOT NULL DEFAULT 0,
    SCREEN_ID     VARCHAR(30)  NOT NULL,
    BUTTON_ID     VARCHAR(30)  NOT NULL,
    UI_VALID      SMALLINT     NOT NULL DEFAULT 0,
    LOGGED_AT     VARCHAR(40)  NOT NULL,
    PRIMARY KEY (ACT_ID),
    KEY IDX_BMNA_MIN (MINUTES_ID, ACT_ID),
    KEY IDX_BMNA_ACTOR (ACTOR_EMP_NO, ACT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
