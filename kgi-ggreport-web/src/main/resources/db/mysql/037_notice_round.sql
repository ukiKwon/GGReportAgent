CREATE TABLE NOTICE_ROUND (
    INSTITUTION_ID   VARCHAR(64)  NOT NULL,
    ROUND_SEQ        INT          NOT NULL,
    SOURCE_CD        VARCHAR(20)  NOT NULL,
    ANCHOR_LAST_BID  VARCHAR(30),
    TARGET_TERM_YEAR SMALLINT,
    OPENED_AT        VARCHAR(40)  NOT NULL,
    OPENED_BY        VARCHAR(7)   NOT NULL,
    CLOSED_AT        VARCHAR(40),
    CLOSE_REASON_CD  VARCHAR(20),
    CLOSED_BY        VARCHAR(7),
    CLOSED_LAST_BID  VARCHAR(30),
    PRIMARY KEY (INSTITUTION_ID, ROUND_SEQ),
    KEY IDX_NR_OPEN (CLOSED_AT, INSTITUTION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE NOTICE_ROUND_LOG (
    INSTITUTION_ID     VARCHAR(64)  NOT NULL,
    ROUND_SEQ          INT          NOT NULL,
    REV_NO             INT          NOT NULL,
    STATUS_CD          VARCHAR(20)  NOT NULL,
    PREV_STATUS_CD     VARCHAR(20),
    OPINION            VARCHAR(500),
    NEXT_CHECK_DATE    VARCHAR(10),
    PREV_NEXT_CHECK    VARCHAR(10),
    ACTIVE_PREP        SMALLINT     NOT NULL DEFAULT 0,
    ACTIVE_PREP_STATE  VARCHAR(30),
    SNAP_DUE_DATE      VARCHAR(10),
    SNAP_DUE_BASIS     VARCHAR(20),
    SNAP_DUE_CONFIRMED SMALLINT     NOT NULL DEFAULT 0,
    SNAP_AUTO_KIND     VARCHAR(20),
    SNAP_AUTO_DAYS     INT,
    SNAP_LAST_BID      VARCHAR(30),
    HANDLER_EMP_NO     VARCHAR(7)   NOT NULL,
    HANDLER_NAME       VARCHAR(50)  NOT NULL,
    EMP_VERIFIED       SMALLINT     NOT NULL DEFAULT 0,
    SCREEN_ID          VARCHAR(30)  NOT NULL,
    BUTTON_ID          VARCHAR(30)  NOT NULL,
    UI_VALID           SMALLINT     NOT NULL DEFAULT 0,
    HANDLED_AT         VARCHAR(40)  NOT NULL,
    PRIMARY KEY (INSTITUTION_ID, ROUND_SEQ, REV_NO),
    KEY IDX_NRL_STATUS (STATUS_CD, NEXT_CHECK_DATE),
    KEY IDX_NRL_HANDLER (HANDLER_EMP_NO, HANDLED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

