CREATE TABLE INST_EDIT_LOG (
    LOG_ID         BIGINT       NOT NULL AUTO_INCREMENT,
    BATCH_KEY      VARCHAR(36)  NOT NULL,
    INSTITUTION_ID VARCHAR(64)  NOT NULL,
    FIELD_CD       VARCHAR(30)  NOT NULL,
    OLD_VAL        VARCHAR(60),
    NEW_VAL        VARCHAR(60),
    SRC_URL        VARCHAR(500),
    SRC_NO         VARCHAR(50),
    ACTOR_EMP_NO   VARCHAR(7),
