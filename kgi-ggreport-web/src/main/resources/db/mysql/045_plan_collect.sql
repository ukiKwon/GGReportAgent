SET NAMES utf8mb4;

CREATE TABLE PLAN_COLLECT_REQ (
    INSTITUTION_ID    VARCHAR(64)   NOT NULL,
    REQ_SEQ           INT           NOT NULL,
    REQ_KEY           VARCHAR(36)   NOT NULL,
    STATUS_CD         VARCHAR(20)   NOT NULL,
    OPEN_INST_ID      VARCHAR(64),
    PREV_DOMAINS      VARCHAR(300),
    REQUESTED_BY      VARCHAR(7)    NOT NULL,
    REQUESTED_AT      VARCHAR(40)   NOT NULL,
    REQ_VERIFIED      SMALLINT      NOT NULL DEFAULT 0,
    RUN_MODE          VARCHAR(10),
    RUN_BY            VARCHAR(7),
    RUN_AT            VARCHAR(40),
    RUN_VERIFIED      SMALLINT      NOT NULL DEFAULT 0,
    RUN_DOMAINS       VARCHAR(300),
    RUN_RESULT_CD     VARCHAR(20),
    JOB_ID            VARCHAR(64),
    APPLIED_IMPORT_ID BIGINT,
    CLOSED_AT         VARCHAR(40),
    CLOSED_BY         VARCHAR(7),
    CLOSE_REASON      VARCHAR(100),
    PRIMARY KEY (INSTITUTION_ID, REQ_SEQ),
    UNIQUE KEY UQ_PCR_KEY (REQ_KEY),
    UNIQUE KEY UQ_PCR_OPEN (OPEN_INST_ID),
    KEY IDX_PCR_STATUS (STATUS_CD, REQUESTED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PLAN_COLLECT_REQUESTER (
    INSTITUTION_ID    VARCHAR(64)   NOT NULL,
    REQ_SEQ           INT           NOT NULL,
    EMP_NO            VARCHAR(7)    NOT NULL,
    REQUESTED_AT      VARCHAR(40)   NOT NULL,
    EMP_VERIFIED      SMALLINT      NOT NULL DEFAULT 0,
    CANCELED_AT       VARCHAR(40),
    PRIMARY KEY (INSTITUTION_ID, REQ_SEQ, EMP_NO),
    KEY IDX_PCRQ_EMP (EMP_NO, REQUESTED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

