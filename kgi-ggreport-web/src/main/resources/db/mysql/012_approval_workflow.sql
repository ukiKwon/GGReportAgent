CREATE TABLE APPROVAL_DEPUTY (
    DEPUTY_ID        BIGINT       NOT NULL AUTO_INCREMENT,
    PRINCIPAL_EMP_NO VARCHAR(7)   NOT NULL,
    DEPUTY_EMP_NO    VARCHAR(7)   NOT NULL,
    START_DATE       VARCHAR(10)  NOT NULL,
    END_DATE         VARCHAR(10)  NOT NULL,
    REASON           VARCHAR(200),
    CREATED_BY       VARCHAR(7),
    CREATED_AT       VARCHAR(40)  NOT NULL,
    CANCELLED_AT     VARCHAR(40),
    CANCELLED_BY     VARCHAR(7),
    PRIMARY KEY (DEPUTY_ID),
    KEY IDX_AD_PRINCIPAL (PRINCIPAL_EMP_NO),
    KEY IDX_AD_DEPUTY (DEPUTY_EMP_NO),
    CONSTRAINT FK_AD_PRINCIPAL FOREIGN KEY (PRINCIPAL_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT FK_AD_DEPUTY FOREIGN KEY (DEPUTY_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT CK_AD_NOT_SELF CHECK (PRINCIPAL_EMP_NO <> DEPUTY_EMP_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE APPROVAL_REQUEST (
    REQ_ID           BIGINT       NOT NULL AUTO_INCREMENT,
    REQ_TYPE         VARCHAR(30)  NOT NULL,
    REQUESTER_EMP_NO VARCHAR(7)   NOT NULL,
    TITLE            VARCHAR(200) NOT NULL,
    PAYLOAD          TEXT,
    STATUS           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    CURRENT_STEP     SMALLINT     NOT NULL DEFAULT 1,
    RESULT_NOTE      VARCHAR(300),
    CREATED_AT       VARCHAR(40)  NOT NULL,
    DECIDED_AT       VARCHAR(40),
    PRIMARY KEY (REQ_ID),
    KEY IDX_AR_REQUESTER (REQUESTER_EMP_NO, REQ_ID),
    KEY IDX_AR_STATUS (STATUS, REQ_ID),
    CONSTRAINT FK_AR_REQUESTER FOREIGN KEY (REQUESTER_EMP_NO) REFERENCES USERS (EMP_NO),
    CONSTRAINT CK_AR_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE APPROVAL_STEP (
    STEP_ID          BIGINT       NOT NULL AUTO_INCREMENT,
    REQ_ID           BIGINT       NOT NULL,
    STEP_NO          SMALLINT     NOT NULL,
    KIND             VARCHAR(10)  NOT NULL,
    APPROVER_EMP_NO  VARCHAR(7),
    STATUS           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    ACTED_BY         VARCHAR(7),
    ACTED_AS_DEPUTY  SMALLINT     NOT NULL DEFAULT 0,
    COMMENT_TEXT     VARCHAR(500),
    ACTED_AT         VARCHAR(40),
    PRIMARY KEY (STEP_ID),
    UNIQUE KEY UQ_AS_REQ_STEP (REQ_ID, STEP_NO),
    KEY IDX_AS_APPROVER (APPROVER_EMP_NO, STATUS),
    CONSTRAINT FK_AS_REQ FOREIGN KEY (REQ_ID) REFERENCES APPROVAL_REQUEST (REQ_ID),
    CONSTRAINT CK_AS_KIND CHECK (KIND IN ('LINE', 'ADMIN')),
    CONSTRAINT CK_AS_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'SKIPPED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
