SET NAMES utf8mb4;

CREATE TABLE INST_PLAN_IMPORT (
    IMPORT_ID         BIGINT        NOT NULL AUTO_INCREMENT,
    INSTITUTION_ID    VARCHAR(64)   NOT NULL,
    ORIGIN_CD         VARCHAR(20)   NOT NULL,
    FILE_DATE         VARCHAR(10)   NOT NULL,
    FILE_SHA256       VARCHAR(64)   NOT NULL,
    FILE_BYTES        BIGINT        NOT NULL,
    ITEM_COUNT        INT           NOT NULL,
    DOC_COUNT         SMALLINT      NOT NULL,
    WARN_COUNT        INT           NOT NULL DEFAULT 0,
    BATCH_ID          VARCHAR(64),
    IMPORTED_BY       VARCHAR(7)    NOT NULL,
    IMPORTED_AT       VARCHAR(40)   NOT NULL,
    IMPORTED_VERIFIED SMALLINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (IMPORT_ID),
    KEY IDX_IPI_INST (INSTITUTION_ID, IMPORT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_PLAN_DOC (
    DOC_ID          BIGINT        NOT NULL AUTO_INCREMENT,
    IMPORT_ID       BIGINT        NOT NULL,
    INSTITUTION_ID  VARCHAR(64)   NOT NULL,
    DOC_SEQ         SMALLINT      NOT NULL,
    TITLE           VARCHAR(200)  NOT NULL,
    SRC_KIND_CD     VARCHAR(20)   NOT NULL,
    PERIOD_FROM     SMALLINT      NOT NULL,
    PERIOD_TO       SMALLINT      NOT NULL,
    SRC_URL         VARCHAR(1000),
    URL_MISSING     SMALLINT      NOT NULL DEFAULT 0,
    CHECKED_ON      VARCHAR(10)   NOT NULL,
    COLLECTOR_AGENT VARCHAR(60)   NOT NULL,
    PAGE_RANGE      VARCHAR(20),
    NOTE            VARCHAR(500),
    PRIMARY KEY (DOC_ID),
    KEY IDX_IPD_IMPORT (IMPORT_ID, DOC_SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_PLAN_ITEM (
    ITEM_ID          BIGINT        NOT NULL AUTO_INCREMENT,
    DOC_ID           BIGINT        NOT NULL,
    IMPORT_ID        BIGINT        NOT NULL,
    INSTITUTION_ID   VARCHAR(64)   NOT NULL,
    ROW_NO           INT           NOT NULL,
    FIELD_NO         VARCHAR(20),
    FIELD_NAME       VARCHAR(100),
    ITEM_NO          VARCHAR(50)   NOT NULL,
    PARENT_NO        VARCHAR(50),
    ITEM_NAME        VARCHAR(300)  NOT NULL,
    CONTENT          VARCHAR(1000),
    BUDGET_STATE_CD  VARCHAR(20)   NOT NULL,
    BUDGET_AMOUNT    DECIMAL(18,3),
    BUDGET_UNIT_CD   VARCHAR(20),
    BUDGET_YEARS     VARCHAR(300),
    PAGE_NO          VARCHAR(20),
    CHECK_CD         VARCHAR(20)   NOT NULL,
    PROGRESS_CD      VARCHAR(20),
    EXEC_RATE        DECIMAL(4,1),
    NOTE             VARCHAR(500),
    PRIMARY KEY (ITEM_ID),
    KEY IDX_IPT_DOC (DOC_ID, ROW_NO),
    KEY IDX_IPT_IMPORT (IMPORT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE INST_PLAN_ACT (
    ACT_ID         BIGINT        NOT NULL AUTO_INCREMENT,
    INSTITUTION_ID VARCHAR(64)   NOT NULL,
    IMPORT_ID      BIGINT,
    ACTION_CD      VARCHAR(30)   NOT NULL,
    OUTCOME        VARCHAR(20)   NOT NULL,
    ITEM_COUNT     INT,
    FILE_SHA256    VARCHAR(64),
    ACTOR_EMP_NO   VARCHAR(7),
    EMP_VERIFIED   SMALLINT      NOT NULL DEFAULT 0,
    SCREEN_ID      VARCHAR(30)   NOT NULL,
    BUTTON_ID      VARCHAR(30)   NOT NULL,
    UI_VALID       SMALLINT      NOT NULL DEFAULT 0,
    LOGGED_AT      VARCHAR(40)   NOT NULL,
    PRIMARY KEY (ACT_ID),
    KEY IDX_IPA_INST (INSTITUTION_ID, ACT_ID),
    KEY IDX_IPA_ACTOR (ACTOR_EMP_NO, LOGGED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

