-- Q1 고아 공고(기관 없음)
SELECT b.BID_CASE_ID FROM BID_CASES b
 WHERE NOT EXISTS (SELECT 1 FROM INSTITUTIONS i WHERE i.INSTITUTION_ID = b.INSTITUTION_ID);

-- Q2 고아 작업(공고 없음)
SELECT t.TASK_ID FROM TASKS t
 WHERE NOT EXISTS (SELECT 1 FROM BID_CASES b WHERE b.BID_CASE_ID = t.BID_CASE_ID);

-- Q3 고아 메시지(작업 없음)
SELECT m.MESSAGE_ID FROM MESSAGES m
 WHERE NOT EXISTS (SELECT 1 FROM TASKS t WHERE t.TASK_ID = m.TASK_ID);

-- Q4 고아 실행 / 단계
SELECT r.RUN_ID FROM ORCH_RUN r
 WHERE NOT EXISTS (SELECT 1 FROM INSTITUTIONS i WHERE i.INSTITUTION_ID = r.INSTITUTION_ID);
SELECT r.RUN_ID FROM ORCH_RUN r
 WHERE r.BID_CASE_ID IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM BID_CASES b WHERE b.BID_CASE_ID = r.BID_CASE_ID);
SELECT s.STEP_ID FROM ORCH_STEP s
 WHERE NOT EXISTS (SELECT 1 FROM ORCH_RUN r WHERE r.RUN_ID = s.RUN_ID);

-- Q5 고아 벡터(청크 없음)
SELECT v.CHUNK_ID FROM VECTORS v
 WHERE NOT EXISTS (SELECT 1 FROM CHUNKS c WHERE c.CHUNK_ID = v.CHUNK_ID);

-- Q6 사번이 USERS 에 없음(결재 요청자·대결·메뉴 권한·상위 결재자)
SELECT 'AR' AS T, CAST(r.REQ_ID AS CHAR) AS K FROM APPROVAL_REQUEST r
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = r.REQUESTER_EMP_NO)
UNION ALL
SELECT 'AD', CAST(d.DEPUTY_ID AS CHAR) FROM APPROVAL_DEPUTY d
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = d.PRINCIPAL_EMP_NO)
    OR NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = d.DEPUTY_EMP_NO)
UNION ALL
SELECT 'UMP', p.EMP_NO FROM USER_MENU_PERMS p
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = p.EMP_NO)
UNION ALL
SELECT 'USR', x.EMP_NO FROM USERS x
 WHERE x.APPROVER_EMP_NO IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = x.APPROVER_EMP_NO);

-- Q7 중복(UNIQUE 를 쓰지 않는 경로에서 필수. 지금은 제약이 막으므로 0행)
SELECT BID_CASE_ID, TEAM, COUNT(*) AS N FROM TASKS GROUP BY BID_CASE_ID, TEAM HAVING COUNT(*) > 1;
SELECT SOURCE_SLUG, NOTICE_ID, COUNT(*) AS N FROM BID_CASES
 WHERE SOURCE_SLUG IS NOT NULL AND NOTICE_ID IS NOT NULL
 GROUP BY SOURCE_SLUG, NOTICE_ID HAVING COUNT(*) > 1;
SELECT REQ_ID, STEP_NO, COUNT(*) AS N FROM APPROVAL_STEP GROUP BY REQ_ID, STEP_NO HAVING COUNT(*) > 1;
SELECT RUN_ID, SEQ_NO, COUNT(*) AS N FROM ORCH_STEP GROUP BY RUN_ID, SEQ_NO HAVING COUNT(*) > 1;

-- Q8 이사회 양식(버전의 양식 없음 / 사용 기록의 버전·요청 없음)
SELECT v.FORM_ID FROM BOARD_FORM_VER v
 WHERE NOT EXISTS (SELECT 1 FROM BOARD_FORM f WHERE f.FORM_ID = v.FORM_ID);
SELECT u.USE_ID FROM BOARD_FORM_USE u
 WHERE NOT EXISTS (SELECT 1 FROM BOARD_FORM_VER v WHERE v.FORM_ID = u.FORM_ID AND v.VER_NO = u.VER_NO);
SELECT u.USE_ID FROM BOARD_FORM_USE u
 WHERE NOT EXISTS (SELECT 1 FROM APPROVAL_REQUEST r WHERE r.REQ_ID = u.REQ_ID);

-- Q9 기관당 활성 실행이 둘 이상(UNIQUE 가 막으므로 항상 0. UNIQUE 를 못 쓰는 경로에서 필수)
SELECT ACTIVE_INSTITUTION_ID, COUNT(*) AS N FROM ORCH_RUN
 WHERE ACTIVE_INSTITUTION_ID IS NOT NULL GROUP BY ACTIVE_INSTITUTION_ID HAVING COUNT(*) > 1;

-- Q10 경과 처리: 기관 없음 / 미등록 상태 코드 / 미등록 처리자
SELECT f.INSTITUTION_ID, f.DUE_DATE, f.REV_NO FROM NOTICE_FOLLOWUP f
 WHERE NOT EXISTS (SELECT 1 FROM INSTITUTIONS i WHERE i.INSTITUTION_ID = f.INSTITUTION_ID);
SELECT f.INSTITUTION_ID, f.DUE_DATE, f.REV_NO FROM NOTICE_FOLLOWUP f
 WHERE NOT EXISTS (SELECT 1 FROM COMMON_CODE c WHERE c.CODE_GROUP = 'NOTICE_STATUS' AND c.CODE = f.STATUS_CD);
SELECT f.INSTITUTION_ID, f.DUE_DATE, f.REV_NO FROM NOTICE_FOLLOWUP f
 WHERE NOT EXISTS (SELECT 1 FROM USERS u WHERE u.EMP_NO = f.HANDLER_EMP_NO);

-- Q11 경과 처리 REV_NO 결번(같은 기관·예정일에서 1..n 연속이어야 한다)
SELECT INSTITUTION_ID, DUE_DATE, COUNT(*) AS N, MAX(REV_NO) AS MX FROM NOTICE_FOLLOWUP
 GROUP BY INSTITUTION_ID, DUE_DATE HAVING COUNT(*) <> MAX(REV_NO);

