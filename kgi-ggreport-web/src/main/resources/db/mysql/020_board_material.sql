CREATE TABLE BOARD_MATERIAL (
    MATERIAL_ID     BIGINT       NOT NULL AUTO_INCREMENT,
    BID_CASE_ID     VARCHAR(64)  NOT NULL,
    INSTITUTION_ID  VARCHAR(64)  NOT NULL,
    BOARD_YEAR      SMALLINT     NOT NULL,
    STATUS_CD       VARCHAR(20)  NOT NULL DEFAULT 'PREP',
    RESULT_CD       VARCHAR(20),
    MEETING_DATE    VARCHAR(10),
    SUBMIT_REQ_ID   BIGINT,
    SUBMIT_SNAP     INT,
    CONFIRMED_SNAP  INT,
    CONFIRMED_BY    VARCHAR(7),
    CONFIRMED_AT    VARCHAR(40),
    FORM_ID         VARCHAR(50)  NOT NULL,
    FORM_VER        INT          NOT NULL DEFAULT 0,
    CUR_SNAP        INT          NOT NULL DEFAULT 0,
    LAST_SAVED_BY   VARCHAR(7),
    LAST_SAVED_AT   VARCHAR(40),
    CREATED_BY      VARCHAR(7)   NOT NULL,
    CREATED_AT      VARCHAR(40)  NOT NULL,
    UPDATED_BY      VARCHAR(7)   NOT NULL,
    UPDATED_AT      VARCHAR(40)  NOT NULL,
    PRIMARY KEY (MATERIAL_ID),
    KEY IDX_BM_CASE (BID_CASE_ID),
    KEY IDX_BM_INST (INSTITUTION_ID, BOARD_YEAR),
    KEY IDX_BM_STATUS (STATUS_CD, MEETING_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MATERIAL_SNAP (
    MATERIAL_ID     BIGINT       NOT NULL,
    SNAP_NO         INT          NOT NULL,
    VALUES_JSON     LONGTEXT     NOT NULL,
    NOTE            VARCHAR(200),
    SAVED_BY        VARCHAR(7)   NOT NULL,
    SAVED_AT        VARCHAR(40)  NOT NULL,
    PRIMARY KEY (MATERIAL_ID, SNAP_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MATERIAL_LOG (
    LOG_ID          BIGINT       NOT NULL AUTO_INCREMENT,
    MATERIAL_ID     BIGINT       NOT NULL,
    EVENT_CD        VARCHAR(20)  NOT NULL,
    FROM_STATUS     VARCHAR(20),
    TO_STATUS       VARCHAR(20),
    FROM_RESULT     VARCHAR(20),
    TO_RESULT       VARCHAR(20),
    MEETING_DATE    VARCHAR(10),
    FROM_EMP_NO     VARCHAR(7),
    TO_EMP_NO       VARCHAR(7),
    REQ_ID          BIGINT,
    REASON          VARCHAR(200),
    ACTOR_EMP_NO    VARCHAR(7)   NOT NULL,
    EMP_VERIFIED    SMALLINT     NOT NULL DEFAULT 0,
    LOGGED_AT       VARCHAR(40)  NOT NULL,
    PRIMARY KEY (LOG_ID),
    KEY IDX_BML_MAT (MATERIAL_ID, LOG_ID),
    KEY IDX_BML_REQ (REQ_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE BOARD_MATERIAL_ACT (
    ACT_ID          BIGINT       NOT NULL AUTO_INCREMENT,
    MATERIAL_ID     BIGINT       NOT NULL,
    BID_CASE_ID     VARCHAR(64)  NOT NULL,
    ACTION_CD       VARCHAR(20)  NOT NULL,
    OUTCOME         VARCHAR(20)  NOT NULL,
    STATUS_CD       VARCHAR(20)  NOT NULL,
    RESULT_CD       VARCHAR(20),
    SNAP_NO         INT,
    ACTOR_EMP_NO    VARCHAR(7),
    EMP_VERIFIED    SMALLINT     NOT NULL DEFAULT 0,
    SCREEN_ID       VARCHAR(30)  NOT NULL,
    BUTTON_ID       VARCHAR(30)  NOT NULL,
    UI_VALID        SMALLINT     NOT NULL DEFAULT 0,
    LOGGED_AT       VARCHAR(40)  NOT NULL,
    PRIMARY KEY (ACT_ID),
    KEY IDX_BMA_MAT (MATERIAL_ID, ACT_ID),
    KEY IDX_BMA_ACTOR (ACTOR_EMP_NO, ACT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

