package com.kbstar.kgi.ggreport.web.llm;

/**
 * 경유지(회사 공통 API 게이트웨이) OAuth 토큰 공급자 — <b>인터페이스만 동결, 구현은 비어 있다.</b>
 *
 * <p>규격이 <b>문의 6</b> 회신으로 정해진다(서비스 계정 방식인지 사용자 토큰 위임인지,
 * 토큰 수명·갱신 절차, 게이트웨이가 인증을 완결하는지 뒤쪽 서비스도 재검증해야 하는지).
 * 회신 전에는 이 자리만 두고 구현을 비운다 — 설계 §6-C·계획 Task 4.4 가 그렇게 정했다.
 *
 * <p>⚠️ <b>이 시스템에는 현재 인증이 전혀 없다.</b> 문의 6의 ⓒ(재검증 필요 여부)가
 * "필요하다"로 오면 <b>인증 코드가 통째로 새로 생긴다</b> — 그때는 이 인터페이스가
 * 아니라 별도 과제다.
 *
 * <p><b>토큰 취급 규칙</b>(설계 §6-C, 어기면 사고다):
 * <ul>
 *   <li>메모리에만 둔다 — 파일·DB·설정에 쓰지 않는다</li>
 *   <li><b>로그·{@code messages} 기록·예외 메시지에 싣지 않는다</b></li>
 *   <li>만료 <b>전에</b> 선제 갱신한다. 만료를 기다렸다 401 을 받는 것은 최후 수단이다</li>
 * </ul>
 */
public interface TokenProvider {

    /**
     * 지금 쓸 수 있는 Bearer 토큰. 캐시·선제 갱신은 구현이 알아서 한다.
     *
     * @throws LlmAuthException 토큰을 얻지 못했을 때. <b>폴백을 태우지 않는 갈래</b>다
     *                          — 모델을 바꿔도 토큰은 그대로이기 때문이다.
     */
    String bearerToken();

    /**
     * 401 을 받았을 때 캐시를 버리라고 알린다. 호출부는 이 뒤에 <b>딱 한 번</b> 재시도한다.
     *
     * <p>⚠️ 무한 재시도로 만들지 말 것 — 토큰이 정말 발급 안 되는 상황에서
     * 게이트웨이를 두드리는 루프가 된다.
     */
    void invalidate();
}
