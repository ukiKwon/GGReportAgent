const test = require('node:test'), assert = require('node:assert');
const { fmtLaps } = require('../fmt.js');
const CASES = [
  [0, '0'], [999, '999'], [1234, '1,234'], [9999, '9,999'],
  [10000, '10천'], [12345, '12.3천'], [12350, '12.4천'], [15000, '15천'],
  [99949, '99.9천'], [99950, '100천'],
  [999499, '999.5천'], [999500, '999.5천'], [999949, '999.9천'], [999950, '1백만'], // 승격 경계
  [1000000, '1백만'], [2450000, '2.5백만'], [1234567, '1.2백만'],
  [999999999, '1십억'], [1000000000, '1십억'], [1234567890, '1.2십억'],
  [999900000000, '999.9십억'], [1e12, '1,000십억'],
  [NaN, '0'], [-5, '0'], [undefined, '0'], ['12', '12'], [1500.7, '1,500'],
];
for (const [inp, out] of CASES) test('fmtLaps(' + String(inp) + ') = ' + out, () => assert.strictEqual(fmtLaps(inp), out));
